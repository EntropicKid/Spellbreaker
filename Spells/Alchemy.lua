-- ОТКУДА ЭТО. Составлено игроками вручную через окно создания и
-- перенесено сюда из их сохранёнок: имена, описания, иконки и сроки —
-- авторские.
--
-- ЧИСЛА ТОЖЕ АВТОРСКИЕ. Механических блоков у этих эффектов не было:
-- бонусы стояли ТЕКСТОМ в описании («Бонус "Броня": +25»), то есть
-- зелье не делало ничего, а следил за ним Ведущий. Блоки собраны
-- РАЗБОРОМ ЭТИХ ЖЕ ОПИСАНИЙ — ни одно число не придумано, все взяты из
-- того, что автор написал игроку. Разойдись они с текстом — вышло бы
-- худшее из возможного: карточка обещает одно, движок делает другое.
--
-- ДВЕНАДЦАТЬ ЭФФЕКТОВ ОСТАЛИСЬ БЕЗ БЛОКОВ, и это не пропуск. В их
-- описаниях чисел нет вовсе: «неуязвимость к оглушению», «дышит чем
-- угодно», «снимается 1 отрицательный эффект». Такое не выражается
-- каналами mods/stats и отыгрывается Ведущим — как и было задумано.
--
-- ЧТО ДОБАВЛЕНО ПРИ ПЕРЕНОСЕ, и только это:
--   isItem = true        — предмет, а не заклинание: своя колонка, свои
--                          три ячейки, своя вкладка (см. Core/Items.lua);
--   profession = "alchemy" — чьё ремесло;
--   stack                — сколько склянок влезает в одну ячейку сумки.
--                          Выведено ИЗ НАЗВАНИЯ по слову силы: слабое и
--                          простое носят пачками (10 и 8), обычное — 5,
--                          сильное — 2, мощное и сильнейшее — по одному.
--                          Это ЗАГОТОВКА, а не решение по балансу:
--                          правило механическое, а сколько чего носить —
--                          вопрос к автору зелий. Правится поштучно.
--   distance = MELEE     — выпить самому или подойти и напоить. Метать
--                          склянку в толпу умеют не все, поэтому площадь
--                          проставляется поштучно, а не всем подряд.
--
-- КЛАСС У ПРЕДМЕТА НЕ ЗНАЧИТ НИЧЕГО. У авторов там стоял «Друид» —
-- просто потому, что окно создания требует выбрать класс. Предмет не
-- принадлежит школе: его носит кто угодно, и потолок круга к нему не
-- применяется (см. SB.Items).
-- ============================================================
local addonName, SB = ...

local MELEE = SB.Logic and SB.Logic.MELEE_RANGE or 1.5

local function AddItem(t)
    t.isItem     = true
    t.profession = "alchemy"
    t.class      = "Предмет"
    t.level      = 0
    t.isCustom   = nil
    SB.Data.Spells[t.id] = t
end

local function AddEffect(t)
    t.isContainer = true
    t.class       = "Эффект"
    t.level       = 0
    t.isCustom    = nil
    SB.Data.Spells[t.id] = t
end

