-- ============================================================
-- Spells/Conjured.lua — СОТВОРЁННЫЕ ПРЕДМЕТЫ
--
-- Вещи, которые не покупают и не варят, а создают заклинанием прямо в
-- сцене: вода маны, целебный хлеб, камень здоровья, камень душ,
-- чарокамень, самоцвет маны.
--
-- РАНЬШЕ ИХ НЕ БЫЛО ВОВСЕ. «Создание воды маны» вешало на мага бафф, а
-- «выпить воду» означало дождаться, пока бафф спадёт, и забрать выплату
-- из onRemove. Со стороны это выглядело так, будто маг сам светится
-- водой: в сумке ничего не появлялось, поделиться было нечем, а четыре
-- буханки хлеба были одним эффектом с одной выплатой.
--
-- Теперь это предметы и ведут себя как предметы: занимают ячейку в
-- «Предметах», лежат пачкой, расходуются по одной, попадают под
-- «Науку» (см. SB.Items.NoteUsed) и исчезают с Долгим Отдыхом
-- (см. SB.Items.DropConjured).
--
-- ЧТО ЗНАЧАТ ПОЛЯ, которых нет у покупных:
--   conjured = true  — сотворённый: в библиотеке не показывается и в
--                      сумку заранее не кладётся (см. врезку в
--                      Core/Items.lua);
--   stack            — ПОТОЛОК ИЗ ОПИСАНИЯ, а не вес пачки. «Может
--                      поддерживать существование только двух камней
--                      здоровья» — это stack = 2, и повторный каст
--                      доливает ту же ячейку, а не берёт вторую.
--
-- ЧИСЛА ВЫПЛАТ перенесены из прежних эффектов один в один: там они
-- лежали в onRemove, здесь — в onCast. Баланс не менялся; менялось
-- только то, где вещь находится.
-- ============================================================
local addonName, SB = ...

local MELEE = SB.Logic and SB.Logic.MELEE_RANGE or 2.5

local function AddConjured(t)
    t.isItem     = true
    t.conjured   = true
    t.class      = "Предмет"
    t.level      = 0
    t.resistable = false
    t.distance   = t.distance or MELEE
    SB.Data.Spells[t.id] = t
end

-- ── МАГ ──────────────────────────────────────────────────

AddConjured({
    id    = "item_mana_water",
    name  = "Вода маны",
    key   = "Сотворённое",
    icon  = "Interface\\Icons\\INV_Potion_97",
    stack = 2,
    -- «Восстанавливает одну ячейку заклинания до 3-го уровня». Ячейка —
    -- это ресурс каста, а не мана: у мага они разные, и путать их
    -- нельзя. Тройка — ровно то, что стояло в прежнем onRemove.
    onCast = { mana = 3 },
    description = "Флакон прозрачной воды, в которой растворена сила. " ..
        "Выпитая, она возвращает часть запаса.\n\n" ..
        "Создаётся заклинанием «Создание воды маны». Исчезает с Долгим Отдыхом.",
})

