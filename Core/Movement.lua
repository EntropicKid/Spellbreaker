-- ============================================================

--- МЕТРЫ ДЛЯ ПОКАЗА — ДО ДЕСЯТОЙ. Целые скрывали, сколько на самом деле
--- набежало: 2.5 м показывались тройкой, и шаг в полметра выглядел как
--- скачок на метр. Лишний «.0» у целых отбрасываем: «5.3/27», а не
--- «5.3/27.0».
--- @return string
function SB.Movement.FormatMeters(v)
    local s = string.format("%.1f", tonumber(v) or 0)
    return (s:gsub("%.0$", ""))
end

-- ============================================================
-- ПРИКОЛ СВОЕГО ХОДА
--
-- Отдельный флаг, а не «дописать moveDistance до предела», и причин
-- две. Предел ходит: «Спринт» его поднимает, замедление роняет, Ведущий
-- переписывает, — и записанное число разошлось бы с ним в тот же миг.
-- Вторая важнее: прикол и упор ОТВЕЧАЮТ ПО-РАЗНОМУ на вопрос «можно ли
-- действовать» (см. BlocksAction), и по одному числу их было бы не
-- отличить.
--
-- Флаг лежит в сохранёнке рядом с путём: /reload посреди своего хода не
-- должен возвращать метры, которых в этом окне нет.
-- ============================================================

--- Обездвижен ли персонаж прямо сейчас правилом своего хода.
--- @return boolean
function SB.Movement.IsPinned()
    local d = db()
    if not (d and d.movePinned) then return false end
    -- Режим мог смениться, пока флаг лежал в сохранёнке: «все сразу»
    -- своих ходов не знает, и прикалывать там нечего.
    local TO = SB.TurnOrder
    if not (TO and TO.IsActive and TO.IsActive()) then return false end
    if TO.GetMode and TO.GetMode() == "all" then return false end
    return true
end

--- Свой ход начался: запас на это время обнуляется.
function SB.Movement.PinTurn()
    local d = db()
    if not d or d.movePinned then return end
    d.movePinned = true
    SB.Events.Fire(SB.E.MOVEMENT_CHANGED)
end

--- Запас налит доверху: снимается прикол и обнуляется пройденный путь.
--- Зовётся на входе в режим (с отсрочкой), по закрытию своего хода и
--- отовсюду, где раньше стоял ResetDistance.
function SB.Movement.FillBudget()
    local d = db()
    if not d then return end
    d.movePinned = nil
    SB.Movement.ResetDistance()
    SB.Events.Fire(SB.E.MOVEMENT_CHANGED)
end

--- Налить запас через ENTRY_GRACE секунд после включения режима.
--- Отсрочка — половина смысла правила (см. врезку в шапке файла), но
--- если режим за эти секунды успели выключить, лить уже нечего.
function SB.Movement.FillAfterEntry()
    if not C_Timer then SB.Movement.FillBudget() return end
    C_Timer.After(ENTRY_GRACE, function()
        local TO = SB.TurnOrder
        if TO and TO.IsActive and not TO.IsActive() then return end
        SB.Movement.FillBudget()
    end)
end

--- Сколько метров персонаж уже прошёл в текущем ходу.
--- Значение ЗАЖАТО капом: копить путь сверх предела бессмысленно (упор
--- есть упор, «прошёл сто метров» и «прошёл двенадцать» запрещают одно и
--- то же), а на экране 118/12 выглядело бы просто сломанным счётчиком.
function SB.Movement.GetDistance()
    local d = db()
    local walked = (d and tonumber(d.moveDistance)) or 0
    local cap = SB.Movement.GetCap()
    -- ПРИКОЛ ЧИТАЕТСЯ ПОЛНЫМ СЧЁТЧИКОМ, а не нулём: на экране он значит
    -- ровно то же самое, что выхоженный предел, — «идти нечем». Разница
    -- между ними только в праве действовать, и она объясняется словами
    -- в подсказке, а не числом в бейдже.
    if cap ~= NO_LIMIT and SB.Movement.IsPinned() then return cap end
    if cap ~= NO_LIMIT and walked > cap then return cap end
    return walked
end

--- Личный кап передвижения за ход, в метрах.
--- Хранится в персонаже (Ведущий может выдать больше или меньше), но по
--- умолчанию берётся из конфига, навыка и «мягких» профилей расы и
--- класса — тем же способом, что максимум здоровья и ресурса.
---
--- Висящие эффекты двигают кап в ЛЮБОМ случае, и до, и после ГМ-правки:
--- «Спринт» должен ускорять и того, кому Ведущий выдал свой предел, —
--- иначе персональный предел молча отключал бы всю магию скорости.
--- @return number  метры, либо SB.Movement.NO_LIMIT, если предела нет
function SB.Movement.GetCap()
    local d = db()
    local stored = d and tonumber(d.moveCap)

    -- Предел, снятый Ведущим, эффекты уже не двигают: двигать нечего.
    if stored and stored < 0 then return NO_LIMIT end

    local base = stored or SB.Movement.GetDefaultCap()

    -- ЭФФЕКТЫ ДВИГАЮТ ПРЕДЕЛ В ПРОЦЕНТАХ, а не в метрах, и считаются они
    -- от УЖЕ СОБРАННОГО предела — вместе с «Атлетикой», расой и классом.
    --
    -- Раньше канал был метровым, и одно и то же замедление значило
    -- разное: −6 м отнимало половину хода у обычного персонажа и
    -- четверть у таурена-разбойника с развитой «Атлетикой». То есть
    -- замедление тем слабее, чем быстрее цель, — ровно наоборот тому,
    -- зачем его вешают. Процент бьёт одинаково по всем.
    local slowed = base
    if SB.ActiveEffects and SB.ActiveEffects.GetMod then
        local pct = SB.ActiveEffects.GetMod("movePct")
        if pct ~= 0 then
            -- Округляем к ближайшему: половина от 15 — это 8 метров, а
            -- не 7.5, и в шапке должно стоять целое число.
            slowed = math.floor(base * (1 + pct / 100) + 0.5)
        end
    end

    -- ЗАМЕДЛЕНИЕ НЕ ОБЕЗДВИЖИВАЕТ ПОЛНОСТЬЮ. Предел в ноль означает, что
    -- персонаж упёрся, ещё не сделав шага, — то есть не может ни
    -- применить способность, ни сделать что-либо кроме пропуска хода
    -- (см. IsExhausted и SB.Logic.CanCastNow). Два-три сложившихся
    -- замедления доводили до этого сами собой, и игрок выпадал из сцены
    -- без единого броска на спасение: его ход просто уходил дальше.
    --
    -- Поэтому снизу стоит Config.MoveCapMin: сколько бы ни сложилось
    -- помех, шаг остаётся. Это не поблажка — это разница между «медленно»
    -- и «выбыл».
    --
    -- ГМ-ПРАВКУ ПОЛ НЕ ПОДНИМАЕТ. Если Ведущий выдал персонажу предел
    -- меньше минимума (в том числе ноль — «связан, лежит, вморожен»),
    -- это решение сцены, а не побочный итог арифметики, и переигрывать
    -- его нечем. Пол не может поднять предел выше того, что было ДО
    -- замедления.
    local floorCap = math.min(base, tonumber(SB.Data.Config.MoveCapMin) or 3)

    -- Ниже нуля не уходим, иначе значение столкнулось бы с NO_LIMIT и
    -- замедление внезапно превратилось бы в свободу передвижения.
    return math.max(0, floorCap, slowed)
end

--- Есть ли вообще предел (false — Ведущий его снял).
function SB.Movement.HasLimit()
    return SB.Movement.GetCap() ~= NO_LIMIT
end

--- Кап «по умолчанию» — конфиг, навык и профили, без персональной
--- правки Ведущего и без висящих эффектов.
function SB.Movement.GetDefaultCap()
    local base = tonumber(SB.Data.Config and SB.Data.Config.MoveCap) or 15
    -- «Атлетика» — метр за вложенное очко, в обе стороны (см. Core/Skills.lua).
    if SB.Skills and SB.Skills.GetAthleticsMoveBonus then
        base = base + SB.Skills.GetAthleticsMoveBonus()
    end
    base = base + (SB.Data.GetSoftBonus and SB.Data.GetSoftBonus("moveCap") or 0)
    -- ПОДАВЛЕННАЯ «АТЛЕТИКА» НЕ ОБЕЗДВИЖИВАЕТ — тот же пол, что держит
    -- замедление (Config.MoveCapMin, см. SB.Movement.GetCap). Штраф навыка
    -- появился вместе с метром за очко, и без пола достаточно тяжёлый
    -- дебафф на навык снова выключал бы персонажа из сцены.
    local floor = tonumber(SB.Data.Config and SB.Data.Config.MoveCapMin) or 3
    return math.max(floor, base)
end

--- Сколько метров ещё можно пройти до упора (0, если уже упёрся).
--- Без предела возвращает NO_LIMIT — вызывающему полагается это отличить.
--- В свой ход — ноль: окно передвижения сейчас не ваше (см. IsPinned).
function SB.Movement.GetRemaining()
    local cap = SB.Movement.GetCap()
    if cap == NO_LIMIT then return NO_LIMIT end
    return math.max(0, cap - SB.Movement.GetDistance())
end

--- ЗАПАС В НОГАХ — сколько метров НЕ ВЫХОЖЕНО, без оглядки на прикол.
---
--- Отличается от GetRemaining ровно в свой ход, и разница смысловая.
--- GetRemaining отвечает «сколько можно пройти прямо сейчас» — в свой
--- ход ноль, потому что окно чужое. Здесь вопрос другой: «сколько бега
--- в человеке осталось», и прикол на него не влияет — он про очередь, а
--- не про усталость.
---
--- Спрашивает это побег (SB.Logic.GetFleeOdds): бежать можно только в
--- свой ход, то есть ровно под приколом, и по GetRemaining прибавка к
--- броску была бы всегда нулевой — механика «не потратил метры — легче
--- оторваться» выключилась бы целиком.
--- @return number  метры, либо NO_LIMIT
function SB.Movement.GetReserve()
    local cap = SB.Movement.GetCap()
    if cap == NO_LIMIT then return NO_LIMIT end
    local d = db()
    local walked = (d and tonumber(d.moveDistance)) or 0
    return math.max(0, cap - walked)
end

--- ДЕЙСТВУЕТ ЛИ ПРЕДЕЛ НА ЭТОГО ПЕРСОНАЖА ПРЯМО СЕЙЧАС.
---
--- Две причины, по которым не действует, и обе одинаково полные: метры
--- по-прежнему считаются и видны в шапке, но упор в них ничего не
--- запрещает и ничего не стоит.
---
---   • Ведущий снял предел на сцену (см. TO.SetMoveFree) — общее решение
---     на всех: погоня, отступление по сюжету;
---   • персонаж СБЕЖАЛ ИЗ БОЯ (см. PM.HasFled) — личное и очевидное:
---     очередь его уже не ждёт, и держать беглеца на поводке в двенадцать
---     метров бессмысленно. Хуже того — с включённой усталостью это
---     означало бы, что убегающий умирает от бега, то есть побег
---     оказывается опаснее, чем остаться и драться.
--- @return boolean
function SB.Movement.IsUnlimited()
    if SB.TurnOrder and SB.TurnOrder.IsMoveFree and SB.TurnOrder.IsMoveFree() then
        return true
    end
    if SB.PlayerModel and SB.PlayerModel.HasFled and SB.PlayerModel.HasFled() then
        return true
    end
    return false
end

--- Выбран ли лимит передвижения. Именно это спрашивает ConfirmCast,
--- прежде чем пустить заклинание.
function SB.Movement.IsExhausted()
    if SB.Movement.IsUnlimited() then return false end
    local cap = SB.Movement.GetCap()
    if cap == NO_LIMIT then return false end
    -- Прикол своего хода — тот же нулевой запас, и счётчик обязан
    -- краснеть одинаково: идти нечем в обоих случаях.
    if SB.Movement.IsPinned() then return true end
    -- cap == 0 — полное обездвиживание: 0 >= 0, значит упёрся сразу, ещё
    -- не сделав шага. Так и задумано; см. NO_LIMIT выше о том, почему
    -- ноль больше не путается со «снятым пределом».
    return SB.Movement.GetDistance() >= cap
end

-- ============================================================
-- УПОР В ПРЕДЕЛ ЗАПРЕЩАЕТ ДЕЙСТВИЕ ТОЛЬКО ПРИ ЦЕЛОМ ПРЕДЕЛЕ
--
-- Правило «пробежал всё — либо действуй, либо переводи дух» держится на
-- том, что предел БОЛЬШОЙ: двенадцать метров за круг выхаживаются
-- намеренно, и отдать за них действие — осознанный размен.
--
-- Под замедлением размена нет. Предел падает до трёх (ниже пол не
-- пускает), а три метра игрок проходит, просто переступив с ноги на
-- ногу в чужой ход, — и приходит на свой уже исчерпанным. Ход
-- закрывался сам, ещё до того как игрок успевал что-либо решить:
-- достаточно сильное замедление буквально выключало персонажа из сцены,
-- и снять его было нечем, потому что действовать он тоже не мог.
--
-- ЭТО НАКАЗАНИЕ ДВАЖДЫ ЗА ОДНО. Замедление уже отняло подвижность;
-- отнимать сверх того ещё и действие — значит превращать любой
-- контроль в оглушение, которого никто не накладывал.
--
-- Поэтому упор запрещает действие ТОЛЬКО когда предел не срезан. Срезал
-- его кто угодно — замедление, Ведущий — упор остаётся упором для
-- передвижения (счётчик красный, метры кончились), но ход и действие
-- при игроке.
--
-- ПОДВИЖНОСТИ ЭТО НЕ ДОБАВЛЯЕТ НИ МЕТРА: метры как кончились, так и
-- кончились. Меняется одно — замедленный остаётся участником сцены.
-- ============================================================

--- Мешает ли упор в предел ДЕЙСТВОВАТЬ (а не только идти).
--- Это спрашивают каст, пикер порядка и авто-пропуск; сам счётчик и его
--- цвет по-прежнему смотрят на IsExhausted.
function SB.Movement.BlocksAction()
    -- ПРИКОЛ ДЕЙСТВОВАТЬ НЕ МЕШАЕТ, и это главное, что отличает его от
    -- упора. Свой ход для того и наступил, чтобы им воспользоваться;
    -- запрет здесь означал бы, что пошаговый режим запирает всех и
    -- каждый круг. Метров он всё равно не даёт — шаг в свой ход стоит
    -- усталости (см. врезку в шапке файла).
    if SB.Movement.IsPinned() then return false end
    if not SB.Movement.IsExhausted() then return false end
    -- Предел срезан — значит подвижность уже отобрали, и действие сверху
    -- отбирать нечем.
    local cap = SB.Movement.GetCap()
    if cap ~= NO_LIMIT and cap < SB.Movement.GetDefaultCap() then
        return false
    end
    return true
end

-- ============================================================
-- ЗДЕСЬ БЫЛ АВТОМАТИЧЕСКИЙ ПРОПУСК ХОДА
--
-- Выбранный запас закрывал ход сам: игрок с нулём метров всё равно не
-- мог действовать, и держать такой ход открытым казалось бессмысленным.
--
-- С НЕПОДВИЖНЫМ СВОИМ ХОДОМ ЭТО ПРЕВРАТИЛОСЬ БЫ В МАШИНУ ПРОПУСКОВ:
-- запас обнуляется у КАЖДОГО и КАЖДЫЙ круг (см. врезку в шапке файла), и
-- ход уходил бы раньше, чем игрок успевал поднести курсор к кнопке.
--
-- Но и до правила о своём ходе пропуск отнимал ходы на ровном месте:
-- достаточно было выходить метры в чужой черёд — вдоль стены, обходя
-- союзника, — и свой ход исчезал, не начавшись. Поэтому правило снято
-- целиком, а не оговорено режимом. Упор в предел по-прежнему запрещает
-- ДЕЙСТВИЕ (см. BlocksAction), и этого довольно: ход остаётся при
-- игроке, а закрыть его он волен сам.
-- ============================================================

--- Можно ли сейчас совершить действие.
---
--- МОЛЧА. Ни при упоре в предел, ни при отказе в чат ничего не пишется:
--- состояние и так видно постоянно — бейдж передвижения в шапке краснеет
--- и показывает 12/12, — а строка в чате повторялась бы на каждый шаг
--- вдоль стены и на каждое нажатие «Применить».
---
--- Отдельной функцией, потому что точек входа в «действие» две:
--- SB.Logic.ConfirmCast (обычный каст) и SB.ActiveEffects.Use (клик по
--- активному эффекту). Вторая СПИСЫВАЕТ ПРИМЕНЕНИЕ ДО каста, так что
--- проверять предел уже внутри ConfirmCast поздно — заряд потока сгорел
--- бы впустую на каждом отказе.
--- @return boolean
function SB.Movement.CheckCanAct()
    -- BlocksAction, а не IsExhausted: срезанный предел отнимает метры,
    -- но не действие (см. врезку выше). Это ГЛАВНЫЕ ворота — через них
    -- проходит и обычный каст, и клик по эффекту.
    return not SB.Movement.BlocksAction()
end

-- ============================================================
-- УСТАЛОСТЬ: БЕГ СВЕРХ ПРЕДЕЛА СТОИТ ЗДОРОВЬЯ
--
-- Предел сам по себе запрещает только действие: выбрал двенадцать
-- метров — либо стой, либо пропускай ход. Убежать при этом можно было
-- куда угодно и бесплатно, и «отступить на тридцать метров» ничем не
-- отличалось от «отступить на двенадцать».
--
-- Правило: каждые Config.MoveFatigueStep метров, пройденные ПОСЛЕ
-- упора, стоят Config.MoveFatigueDamage здоровья.
--
-- ЧТО ЗДЕСЬ НЕОЧЕВИДНО:
--
--  • Перебег считается ОТДЕЛЬНЫМ счётчиком (moveOver), а основной путь
--    по-прежнему зажат капом. Иначе в шапке появилось бы «118/12», а
--    решение показывать упор как 12/12 принималось не просто так.
--
--  • Заплаченное запоминается (moveFatiguePaid), а не вычисляется из
--    остатка. Счётчик тикает каждый кадр, и без памяти о выплаченном
--    один и тот же метр списывал бы здоровье снова и снова.
--
--  • Предупреждение приходит РАНЬШЕ первого урона — в момент упора.
--    Бег в игре это примерно 6.4 метра в секунду: при шаге в три метра
--    расплата идёт дважды в секунду, и без окна «остановись сейчас»
--    правило работало бы как ловушка, а не как цена.
--
--  • Павший больше не устаёт. Ноль здоровья — это выход из сцены, и
--    добивать лежащего за то, что его тащат, незачем.
--
--  • Сообщения копятся и уходят пачкой (FATIGUE_REPORT). Две строки в
--    секунду про −1 ХП — это не отчёт, а помеха.
-- ============================================================

-- Как часто отчитываться об усталости в чат, секунд.
local FATIGUE_REPORT = 1.0

local fatigueWarned  = false   -- предупреждали ли в этом ходу
local fatiguePending = 0       -- ХП, о которых ещё не отчитались
local fatigueDueAt   = 0

--- Действует ли усталость сейчас.
---
--- ПО УМОЛЧАНИЮ — ДА, и отдельной галочки «включить усталость» нет.
--- Это не украшение, а половина смысла предела: без цены за бег ПвП
--- сводится к «убегаю и не отвечаю», и никакая очередь ходов этого не
--- ловит. Выключается вместе с самим пределом, одним решением Ведущего
--- на сцену (см. TO.SetMoveFree), — потому что «предела нет» и «за бег
--- сверх предела платят» противоречили бы друг другу.
function SB.Movement.IsFatigueOn()
    if SB.TurnOrder then
        -- В свободной игре метры не копятся вовсе (см. ShouldCount), и
        -- цены за бег там быть не может: персонаж просто идёт по миру.
        if SB.TurnOrder.IsActive and not SB.TurnOrder.IsActive() then return false end
    end
    -- Снятый предел — хоть Ведущим на сцену, хоть собственным побегом —
    -- отменяет и плату за бег: «предела нет» и «за бег сверх предела
    -- платят» противоречили бы друг другу (см. SB.Movement.IsUnlimited).
    if SB.Movement.IsUnlimited() then return false end
    return true
end

--- Сколько метров пройдено СВЕРХ предела в этом ходу.
function SB.Movement.GetOverrun()
    local d = db()
    return (d and tonumber(d.moveOver)) or 0
end

--- Отчёт об усталости — МЕСТНЫЙ, не в рассылку.
---
--- Само изменение здоровья группа и так увидит: PM.GrantHealth шлёт
--- STATUS_CHANGED. А вот строка про метры интересна только тому, кто
--- бежит, и в рейде десяток бегущих превратил бы её в десяток сообщений
--- в секунду — ровно тот шторм, от которого канал уводили.
local function FlushFatigueReport()
    if fatiguePending <= 0 then return end
    local lost = fatiguePending
    fatiguePending = 0
    print(SB.Theme.MSG_TAG .. "[Spellbreaker]|r: " .. SB.Theme.MSG_BAD ..
        string.format("усталость: -%d ХП|r", lost) .. SB.Theme.MSG_BODY ..
        string.format(" (%.0f м сверх предела).|r", SB.Movement.GetOverrun()))
end

--- Записать метры, пройденные сверх предела, и взять за них плату.
---
--- Отдельной функцией, а не строчками внутри шагомера: сюда смотрит
--- прогон без игры (кадров там нет, а правило проверить надо), и здесь
--- же видно всё правило целиком.
--- @param meters number  сколько метров прошли сверх предела за этот кадр
--- @return number  сколько ХП снято этим вызовом
function SB.Movement.AddOverrun(meters)
    meters = tonumber(meters) or 0
    if meters <= 0 or not SB.Movement.IsFatigueOn() then return 0 end

    local d = db()
    if not d then return 0 end

    local PM = SB.PlayerModel
    -- Павший не устаёт: ноль здоровья — уже выход из сцены.
    if PM and PM.IsDowned and PM.IsDowned() then return 0 end

    local cfg   = SB.Data.Config or {}
    local step  = math.max(0.1, tonumber(cfg.MoveFatigueStep) or 3)
    local per   = math.max(0, tonumber(cfg.MoveFatigueDamage) or 1)

    local over = (tonumber(d.moveOver) or 0) + meters
    d.moveOver = over

    local paid  = tonumber(d.moveFatiguePaid) or 0
    local due   = math.floor(over / step)
    local owed  = due - paid
    if owed <= 0 or per <= 0 then return 0 end

    d.moveFatiguePaid = due
    local lost = owed * per
    -- «self»: усталость — плата за свой же бег, а не чужой удар. Пока
    -- она шла общим каналом урона, ею снимался любой эффект с
    -- breakOn.damaged — полиморф стоил одной единицы здоровья и одного
    -- шага за предел (см. врезку у PM.GrantHealth).
    if PM and PM.GrantHealth then PM.GrantHealth(-lost, "self") end

    fatiguePending = fatiguePending + lost
    local now = GetTime()
    if now >= fatigueDueAt then
        fatigueDueAt = now + FATIGUE_REPORT
        FlushFatigueReport()
    end
    return lost
end

--- Предупредить, что дальше начинается плата. Один раз за ход.
local function WarnFatigue()
    if fatigueWarned or not SB.Movement.IsFatigueOn() then return end
    fatigueWarned = true
    if not UIErrorsFrame then return end
    -- ПРИЧИНУ НАЗЫВАЕМ ПРАВИЛЬНО. Под приколом предел не «выбран» —
    -- он просто не ваш в этом окне, и игрок, прочитавший «выбран», пошёл
    -- бы искать, куда делись метры, которых он не тратил.
    UIErrorsFrame:AddMessage(
        SB.Movement.IsPinned()
            and "Ваш ход — передвижения нет: шаг пойдёт в усталость."
            or  "Предел передвижения выбран — дальше пойдёт усталость.",
        1, 0.5, 0.2, 1, 4)
end

-- ============================================================
-- ЧЕРТА ЗАПАСА — КОНЕЦ СВОЕГО ХОДА
--
-- Ключ — «сцена:круг», в котором свой ход закрылся, и лежит он в
-- сохранёнке рядом с самим путём. Не в памяти: иначе /reload после
-- своего хода не узнал бы, что черта уже пройдена, и стёр бы метры,
-- набранные после действия, — бесплатный сброс одной командой.
--
-- Сброс ровно один на ход: отметка «походил» приходит дважды — своя
-- сразу и от Ведущего пакетом, — и второй раз стёр бы то, что пройдено
-- в промежутке.
-- ============================================================

--- Свой ход закрыт: запас на следующий считается отсюда.
--- @param key string  «сцена:круг», в котором ход закрылся
function SB.Movement.NoteTurnClosed(key)
    local d = db()
    if not d or not key then return end
    if d.moveTurnKey == key then return end
    d.moveTurnKey = key
    SB.Movement.ResetDistance()
end

--- Круг сменился. Если свой ход в прошедшем круге так и не закрылся —
--- персонажа не было в очереди (подключился посреди круга), — черты не
--- было вовсе, и путь копился бы без конца. Тогда черта — сам конец
--- круга. У того, чей ход закрылся, здесь ничего не происходит.
--- @param prevKey string  «сцена:круг» прошедшего круга
function SB.Movement.NoteRoundPassed(prevKey)
    local d = db()
    if not d or not prevKey then return end
    if d.moveTurnKey == prevKey then return end
    d.moveTurnKey = prevKey
    SB.Movement.ResetDistance()
end

--- Обнулить пройденный путь. Черта хода (см. выше), отдых, смена режима.
--- ПРИКОЛ СНИМАЕТСЯ ВМЕСТЕ С ПУТЁМ: обнуление запаса и «окно не твоё» —
--- утверждения противоположные, и оставить второе значило бы выдать
--- полный счётчик там, где его только что стёрли.
function SB.Movement.ResetDistance()
    local d = db()
    if not d then return end
    d.movePinned = nil
    -- Долг усталости снимается вместе с путём: перебег — это событие
    -- ОДНОГО хода, и тащить его в следующий значило бы брать плату
    -- дважды за одни и те же метры.
    fatigueWarned = false
    FlushFatigueReport()
    local hadOver = (d.moveOver or 0) ~= 0 or (d.moveFatiguePaid or 0) ~= 0
    d.moveOver, d.moveFatiguePaid = 0, 0
    if (d.moveDistance or 0) == 0 and not hadOver then return end
    d.moveDistance = 0
    SB.Events.Fire(SB.E.MOVEMENT_CHANGED)
end

--- Задать личный кап (ГМ-правка).
--- @param value number|nil  метры; nil — вернуть значение по умолчанию,
---        отрицательное — снять предел совсем (SB.Movement.NO_LIMIT).
function SB.Movement.SetCap(value)
    local d = db()
    if not d then return end
    if value == nil then
        d.moveCap = nil
    else
        local v = tonumber(value) or 0
        d.moveCap = (v < 0) and NO_LIMIT or v
    end
    SB.Movement.InvalidateCapCache()
    SB.Events.Fire(SB.E.MOVEMENT_CHANGED)
end

