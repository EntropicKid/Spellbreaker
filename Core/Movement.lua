-- входит шаг, уже посчитанный по скорости (см. SB.Movement.Step).
local spedSinceSample = false

local function PositionStep()
    if not UnitPosition then return 0 end
    local y, x, _, inst = UnitPosition("player")
    if not x or not y then
        -- Подземелье или поле боя: координат нет вовсе. Сбрасываем
        -- точку отсчёта, иначе на выходе оттуда первый же замер дал бы
        -- разницу через полмира.
        lastX, lastY, lastInst = nil, nil, nil
        return 0
    end

    local px, py, pinst = lastX, lastY, lastInst
    lastX, lastY, lastInst = x, y, inst

    if not px or pinst ~= inst then return 0 end

    local d = math.sqrt((x - px) ^ 2 + (y - py) ^ 2)
    if d > MAX_STEP_YARDS then return 0 end
    return d
end

--- ОДИН КАДР ШАГОМЕРА.
---
--- ВЫНЕСЕН ИЗ ЗАМЫКАНИЯ OnUpdate НАРОЧНО. Пока весь счёт жил внутри
--- обработчика кадра, проверить его было нечем: прогон кадров не
--- рисует, и до кода внутри OnUpdate не достучаться. А считает он
--- механику, а не оформление — предел передвижения, усталость, упор, —
--- и молчаливая ошибка здесь стоит игроку хода.
---
--- Обработчик кадра ниже теперь состоит из одной строки: вызова этой
--- функции. Больше в нём ничего и не должно быть.
--- @param elapsed number  секунд с прошлого кадра
function SB.Movement.Step(elapsed)
    sinceNotify = sinceNotify + elapsed
    local due   = (sinceNotify >= NOTIFY_INTERVAL)
    local speed = CurrentSpeed()
    if speed > 0 then spedSinceSample = true end

    -- САМЫЙ ЧАСТЫЙ КАДР: персонаж стоит, до опроса ещё далеко. Выходим
    -- на двух сравнениях, не трогая ни сохранёнки, ни навыки, ни эффекты.
    if speed <= 0 and not due then return end

    local d = db()
    if not d then return end

    if due or cachedCap == nil then cachedCap = SB.Movement.GetCap() end
    local cap    = cachedCap
    local walked = tonumber(d.moveDistance) or 0

    -- УПЁРСЯ — ПУТЬ БОЛЬШЕ НЕ РАСТЁТ. Он зажимается ровно капом и там
    -- остаётся: сверх предела число ничего не решает (запрет один и тот
    -- же), зато на экране 118/12 выглядело бы сломанным счётчиком.
    --
    -- Метры при этом не выбрасываются: если Ведущий включил усталость,
    -- они уходят в отдельный счётчик перебега и стоят здоровья (см.
    -- SB.Movement.AddOverrun). Выключена — AddOverrun выходит на первой
    -- строке, и кадр остаётся ровно таким же дешёвым, как был.
    local limited = (cap ~= NO_LIMIT)
    -- ПРИКОЛ СВОЕГО ХОДА — ТОТ ЖЕ УПОР ДЛЯ ШАГОМЕРА. Иначе правило
    -- «свой ход неподвижен» держалось бы на честном слове: аддон не
    -- может отнять клавиши, и без цены за шаг можно было бы подойти
    -- вплотную и ударить, ничего не потратив (см. врезку в шапке).
    local capped  = (limited and walked >= cap) or SB.Movement.IsPinned()

    -- ЗАПАСНОЙ ЗАМЕР ПО КООРДИНАТАМ — раз в NOTIFY_INTERVAL и только
    -- когда скорость молчит. Пять раз в секунду вместо шестидесяти:
    -- дешевле, а для шагомера пятая доля секунды — не разница.
    --
    -- Считаем ЗДЕСЬ, а не в общей ветке ниже: там путь прибавляется от
    -- скорости за кадр, а координаты дают уже готовые метры за интервал,
    -- и умножать их на elapsed было бы неверно.
    -- КОРОТКИЙ ШАГ НЕ СЧИТАЕТСЯ ДВАЖДЫ. Раньше условие было «скорость
    -- молчит в кадре опроса», и шаг, начавшийся и кончившийся между двумя
    -- опросами, засчитывался дважды: кадрами по скорости и ещё раз
    -- сдвигом координат, когда к опросу игрок уже стоял. Микрошаг давал
    -- два-три метра вместо одного. Теперь сдвиг засчитывается, только
    -- если скорость молчала ВЕСЬ интервал — то есть персонажа и правда
    -- везли, а не он шёл.
    local carried = 0
    if due then
        local step = PositionStep()
        if speed <= 0 and not spedSinceSample then
            carried = step * YARDS_TO_METERS
        end
        spedSinceSample = false
    end

    if carried > 0 and ShouldCount() then
        if not capped then
            walked = walked + carried
            if limited and walked > cap then
                local over = walked - cap
                walked = cap
                SB.Movement.AddOverrun(over)
            end
            d.moveDistance = walked
            capped = (limited and walked >= cap)
            if capped then WarnFatigue() end
        else
            SB.Movement.AddOverrun(carried)
        end
    end

    if speed > 0 and ShouldCount() then
        -- GetUnitSpeed отдаёт ярды в секунду; текущая скорость — первый
        -- возврат. Накапливаем КАЖДЫЙ кадр (а не раз в 0.2 с): остановка
        -- в середине интервала иначе засчитывалась бы как полный интервал
        -- бега, и путь врал бы в большую сторону на метр с лишним за
        -- каждый рывок.
        local step = speed * elapsed * YARDS_TO_METERS

        if not capped then
            walked = walked + step
            if limited and walked > cap then
                -- Часть шага, ушедшая ЗА предел, — это уже усталость, а
                -- не путь. Без этого кусочка первый метр перебега всегда
                -- терялся бы, а на быстром беге терялось бы до трёх.
                local over = walked - cap
                walked = cap
                SB.Movement.AddOverrun(over)
            end
            d.moveDistance = walked
            capped = (limited and walked >= cap)
            if capped then WarnFatigue() end
        else
            -- УПЁРСЯ. Путь больше не растёт (см. врезку ниже), но метры
            -- продолжают считаться — теперь в долг усталости. Правило
            -- выключено — AddOverrun выйдет на первой строке, и кадр
            -- останется таким же дешёвым, как был.
            SB.Movement.AddOverrun(step)
        end
    end

    if not due then return end
    sinceNotify = 0

    -- Событие шлём только когда есть что показывать: либо игрок движется
    -- и счётчик ещё растёт, либо состояние «упёрся» только что
    -- изменилось. Иначе стоящий на месте (или уже упёртый) персонаж
    -- перерисовывал бы шапку пять раз в секунду вечно.
    if wasExhausted == nil then
        wasExhausted = capped
        return
    end
    -- ОБНОВЛЯЕМ, ЕСЛИ ПУТЬ ВЫРОС, А НЕ ЕСЛИ ИГРОК ДВИЖЕТСЯ ПРЯМО СЕЙЧАС.
    -- Было «скорость больше нуля в кадре опроса». Микрошаг короче пятой
    -- доли секунды в счётчик попадал, а к опросу игрок уже стоял — и
    -- шапку никто не просил перерисоваться. Метры копились невидимо, по
    -- метру-два, и всплывали разом, когда какой-нибудь шаг случайно
    -- приходился на опрос: «прошёл почти весь ящик на нуле, и вдруг 2.2».
    -- Сравнение с показанным ловит любой рост — бегом, координатами,
    -- сколь угодно коротким шагом.
    local walkedNow = tonumber(d.moveDistance) or 0
    local grew = (shownDistance == nil) or (walkedNow ~= shownDistance)
    if grew or capped ~= wasExhausted then
        wasExhausted  = capped
        shownDistance = walkedNow
        SB.Events.Fire(SB.E.MOVEMENT_CHANGED)
    end

end

tracker:SetScript("OnUpdate", function(_, elapsed)
    SB.Movement.Step(elapsed)
end)

