-- ============================================================
-- Core/Movement.lua — ШАГОМЕР И ЛИМИТ ПЕРЕДВИЖЕНИЯ ЗА ХОД
--
-- ЗАЧЕМ. В настольной системе ход состоит из двух вещей: персонаж
-- перемещается и что-то делает. Аддон до сих пор знал только вторую
-- половину — заклинание тратило ход, а перемещение не стоило ничего, и
-- «отбежал на тридцать метров и ударил» было ровно так же дёшево, как
-- «ударил, стоя на месте». Дистанции у заклинаний при этом есть и
-- проверяются (см. SB.Logic.IsSpellInRange), то есть расстояние в
-- системе значит много, а движение — ничего.
--
-- КАК СЧИТАЕТСЯ. Пройденный путь берётся ИНТЕГРИРОВАНИЕМ СКОРОСТИ:
-- каждый кадр к счётчику прибавляется GetUnitSpeed("player") * elapsed.
--
-- Это единственный способ, который работает везде. Очевидные
-- альтернативы не годятся:
--   • UnitPosition("player") — Blizzard режет его в подземельях,
--     на аренах и полях боя: возвращает nil, и шагомер там просто
--     перестал бы считать;
--   • C_Map.GetPlayerMapPosition — то же ограничение плюс нормированные
--     0..1 координаты, которые нужно переводить в ярды по размеру карты,
--     а размер известен не для всех карт.
-- GetUnitSpeed не ограничен ничем, отдаёт ярды в секунду и одинаково
-- честно считает бег, ходьбу, полёт и плавание.
--
-- КОГО ВЕЗУТ — ТОТ ТОЖЕ ПЕРЕМЕЩАЕТСЯ, и это единственное место, где
-- GetUnitSpeed("player") врёт. Персонаж, севший верхом на СУЩЕСТВО
-- (повозка, конь-НПС, чужой транспорт), сам не бежит: собственная его
-- скорость ровно ноль, а по миру он при этом едет. Шагомер молчал, и
-- верхом можно было пересечь всю сцену бесплатно.
--
-- Ловим это двумя способами, и второй нужен именно на приватном
-- сервере:
--   • штатный транспорт (UnitInVehicle) — спрашиваем скорость у того,
--     кто везёт, у юнита "vehicle";
--   • всё остальное — сверяем МИРОВЫЕ КООРДИНАТЫ раз в NOTIFY_INTERVAL.
--     Сервер может усадить персонажа так, что игровой API транспорта об
--     этом не знает вовсе (у эмуляторов это обычное дело), а вот
--     координаты игрока едут вместе с тем, кто его везёт, всегда.
--
-- Координаты остаются ЗАПАСНЫМ путём, а не основным: они молчат в
-- подземельях и на полях боя (см. выше), и точность у них в пять раз
-- грубее. Основным по-прежнему остаётся скорость.
--
-- ЕДИНИЦЫ. GetUnitSpeed отдаёт ЯРДЫ, а вся система говорит в МЕТРАХ
-- (у заклинаний distance = 2.5 / 8.5 / 19). Переводим на месте, тем же
-- коэффициентом, что и проверка дальности в Core/Logic.lua.
--
-- ============================================================
-- КОГДА ЗАПАС ЕСТЬ, А КОГДА ЕГО НЕТ
--
-- ЖАЛОБА, С КОТОРОЙ ПРАВИЛО ПЕРЕПИСАНО: боец ближнего боя в пошаговом
-- режиме не может никого догнать — даже рывком. Разбираться стоит не с
-- числом метров, а с тем, КОГДА они выдаются.
--
-- Прежняя черта — конец своего хода. Значит запас приходил ровно в тот
-- миг, когда заклинатель отыграл: он бил и тут же уходил на полный
-- предел, а догоняющий свои метры уже потратил, подходя. Расстояние
-- восстанавливалось быстрее, чем сокращалось, и ближний бой в пошаговом
-- режиме существовал только по согласию цели.
--
-- ТЕПЕРЬ ОКНО ПЕРЕДВИЖЕНИЯ — ЭТО ЧУЖИЕ ХОДЫ, а свой ход неподвижен:
--
--   1. Пошаговый режим включился — через ENTRY_GRACE секунд запас
--      наливается всем доверху. Пара секунд даётся на то, чтобы игрок
--      успел заметить объявление: метры, пройденные по инерции сразу
--      после команды Ведущего, не должны стоить хода.
--   2. Дошла очередь — запас обнуляется НА ВРЕМЯ СВОЕГО ХОДА. Не
--      «кончился», а «сейчас не твоё окно»: подойти на дистанцию в свой
--      же ход и ударить нельзя, как нельзя и ударить и убежать.
--   3. Походил (или пропустил) — запас снова полон, и тратится он в
--      чужие ходы, наравне со всеми остальными, у кого он в этот момент
--      тоже полон. Вот здесь догоняющий и догоняет.
--
-- ПРИКОЛ НЕ ЗАПРЕЩАЕТ ДЕЙСТВОВАТЬ. Это единственное, что отличает его
-- от честного упора в предел, и отличие принципиальное: свой ход для
-- того и наступил, чтобы им воспользоваться. Запрет на действие при
-- нулевом запасе остался только там, где запас ВЫХОЖЕН (см.
-- SB.Movement.BlocksAction).
--
-- ЧЕМ ПРИКОЛ ДЕРЖИТСЯ. Аддон не может отнять у игрока клавиши — значит
-- шаг в свой ход возможен физически. Стоит он ровно столько же, сколько
-- любой метр сверх предела: усталостью (см. SB.Movement.AddOverrun).
-- Без этой цены правило 2 было бы украшением: подошёл бы вплотную и
-- ударил, ничего не заплатив.
--
-- «ВСЕ СРАЗУ» ЭТОГО НЕ ЗНАЕТ. Там нет очереди, а значит нет и «своего
-- хода», который можно обездвижить: прикалывать пришлось бы весь круг
-- целиком. В этом режиме черта прежняя — конец своего хода
-- (см. SB.Movement.NoteTurnClosed).
--
-- ХОД БОЛЬШЕ НЕ ПРОПУСКАЕТСЯ САМ. Выбранный запас закрывал ход
-- автоматически, и с неподвижным своим ходом это означало бы, что
-- пошаговый режим пропускает ходы всем и каждый круг. Правило снято
-- целиком, а не оговорено: упор в предел запрещает действие — этого
-- достаточно, а закрывать ход за игрока незачем.
--
-- ПРЕДМЕТ — БОНУСНОЕ действие и предела не касается: выпить зелье можно
-- и упёршись в него (см. SB.Logic.IsBonusAction).
-- ============================================================
local addonName, SB = ...
SB.Movement = SB.Movement or {}

-- Тот же коэффициент, что в SB.Logic.IsSpellInRange.
local YARDS_TO_METERS = 0.9144

-- Как часто шлём MOVEMENT_CHANGED. Само накопление идёт КАЖДЫЙ кадр
-- (иначе остановка в середине интервала теряется и путь занижается), а
-- вот перерисовывать шапку 60 раз в секунду незачем.
local NOTIFY_INTERVAL = 0.2

-- Сколько секунд после включения пошагового режима запас наливается
-- заново. Объявление «Пошаговый режим» игрок должен успеть прочитать, и
-- шаги, сделанные по инерции в эти секунды, стоить хода не должны.
local ENTRY_GRACE = 2
SB.Movement.ENTRY_GRACE = ENTRY_GRACE

-- «Предела нет вовсе» — отдельное значение, а НЕ ноль.
--
-- Сначала ноль и означал «ограничение снято», и это было ошибкой:
-- эффекты умеют двигать кап (канал movePct), и достаточно сильный
-- дебафф на замедление обнулял бы предел — то есть СНИМАЛ ограничение
-- вместо того, чтобы обездвижить. Теперь ноль честно значит ноль
-- («шагнул — и действовать уже нечем»), а снятие предела задаётся
-- отдельным значением, до которого арифметике не дотянуться.
local NO_LIMIT = -1
SB.Movement.NO_LIMIT = NO_LIMIT

local function db()
    return SpellbreakerCharDB
end

