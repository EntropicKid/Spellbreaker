--- Собственная скорость либо скорость того, кто везёт.
--- @return number  ярдов в секунду
local function CurrentSpeed()
    local own = GetUnitSpeed("player") or 0
    if own > 0 then return own end
    -- Ноль у себя — возможно, везут. У штатного транспорта скорость
    -- спрашиваем прямо, у него свой юнит-токен.
    if UnitInVehicle and UnitInVehicle("player") then
        return (GetUnitSpeed("vehicle") or 0)
    end
    return 0
end

