-- ============================================================
-- Core/DamageTypes.lua — ТИПЫ УРОНА
--
-- Семь школ урона классического Warcraft, и больше их не было:
--
--   Физический    — сталь, кулак, стрела, брошенный камень;
--   Свет          — кара, освящение, изгнание;
--   Огонь         — пламя, жар, взрыв (включая зелёный огонь Скверны);
--   Природа       — молния, гром, ветер, яд, живая земля;
--   Лёд           — холод, стужа;
--   Тьма          — тень, порча, нежить, зараза;
--   Тайная магия  — чистая магия как таковая: чары, звёзды, мана.
--
-- ЧТО ЭТО ДАЁТ. Ровно одно: игрок видит, ЧЕМ бьёт заклинание, не
-- вчитываясь в описание. «Урон: 7» одинаков у удара мечом и у стрелы
-- тьмы, а за столом это разные вещи — от одного спасает доспех, от
-- другого не спасает ничего, и решает это Ведущий. До сих пор ему
-- приходилось помнить всю библиотеку наизусть.
--
-- ЧТО ТИП СЧИТАЕТ. Изначально он был только подписью, но давно перестал:
-- от него зависят ОБЕ стороны размена — сколько урона доходит до цели
-- (сопротивления, врезка ниже) и сколько его выходит от заклинателя
-- (прибавки к урону, врезка там же). Обе развилки устроены одинаково:
-- общий уровень, магический и школьный.
--
-- ЧЕГО ОН ВСЁ ЕЩЁ НЕ ДЕЛАЕТ: иммунитетов не бывает ни с какой стороны
-- (см. SB.Skills.ApplyResistance), и множителей тоже нет — всё считается
-- плоскими слагаемыми, как и остальная арифметика аддона.
--
-- ПО КАКОМУ ПРАВИЛУ ТИП РАЗДАН. Тип — это то, что ДОХОДИТ ДО ЦЕЛИ, а не
-- то, откуда заклинатель взял силу. Клинок, кулак, стрела — физический,
-- даже если сталь на мгновение вспыхнула Скверной; школа заклинания
-- (поле key) решает по умолчанию, а описание перебивает школу, когда
-- прямо называет урон («получают урон звуком», «дробящий урон»,
-- «начертанный не скверной»).
--
-- ЦВЕТ ЖИВЁТ ЗДЕСЬ, А НЕ В Core/Theme.lua, и это единственное
-- исключение из «все цвета в теме». Причина простая: тип без своего
-- цвета — половина типа. Держи мы их врозь, добавление восьмой школы
-- требовало бы правки двух файлов, и рассинхрон был бы вопросом
-- времени. Цвета взяты из боевого лога самой игры (schoolColoring):
-- игроки узнают их, ничего не заучивая.
--
-- ФИЗИЧЕСКИЙ — БРОНЗА, А НЕ ЖЁЛТЫЙ. В логе Blizzard он жёлтый, но здесь
-- подписи строк («Урон:», «Атака:») уже золотые, и жёлтое число рядом с
-- золотой подписью сливалось бы в одно пятно.
-- ============================================================
local addonName, SB = ...
SB.Data = SB.Data or {}

-- magic — магическая ли школа. Физический единственный, кто нет, и это
-- не мелочь: от него и защищаются иначе (см. врезку о сопротивлениях).
SB.Data.DamageTypes = {
    physical = { id = "physical", name = "Физический",   color = "FFC79C6E", magic = false },
    holy     = { id = "holy",     name = "Свет",         color = "FFFFE680", magic = true  },
    fire     = { id = "fire",     name = "Огонь",        color = "FFFF8000", magic = true  },
    nature   = { id = "nature",   name = "Природа",      color = "FF4DFF4D", magic = true  },
    frost    = { id = "frost",    name = "Лёд",          color = "FF80FFFF", magic = true  },
    shadow   = { id = "shadow",   name = "Тьма",         color = "FF8080FF", magic = true  },
    arcane   = { id = "arcane",   name = "Тайная магия", color = "FFFF80FF", magic = true  },
}

-- ============================================================
-- СОПРОТИВЛЕНИЯ: ТРИ УРОВНЯ, ОТ ОБЩЕГО К ЧАСТНОМУ
--
--   resistAll    — гасит ЛЮБОЙ урон, включая физический;
--   resistMagic  — гасит любую магию, но не сталь;
--   resist<Тип>  — гасит одну школу.
--
-- Они СКЛАДЫВАЮТСЯ, а не выбирается сильнейший: три источника защиты —
-- это три источника защиты. Дворф со своим льдом под аурой паладина
-- держит мороз лучше, чем поодиночке, и удивляться тут нечему.
--
-- У ФИЗИЧЕСКОГО СВОЙ КЛЮЧ ЕСТЬ — resistPhysical. Прежде его не было:
-- считалось, что сопротивление стали — это доспех, и второе, плоское,
-- его обесценит. На деле без ключа защитные чары против оружия («Щит»,
-- «Каменная кожа», стойки) было нечем выразить, кроме резиста ко всему
-- — а тот гасит заодно и магию. Доспех и резист при этом разные вещи и
-- работают по-разному: резист плоский и вечный на время эффекта, доспех
-- — расходуемый запас, и порядок их прежний (сначала резист, потом
-- броня, см. SB.Skills.ApplyResistance). Магическим resistMagic
-- физическое по-прежнему не гасится.
--
-- РЕЗИСТ ГАСИТ ДО НУЛЯ. Пола «единица проходит всегда» здесь нет, и это
-- решение принято после того, как пол сломал главное правило порядка:
-- удар в единицу при резисте в единицу проходил резист насквозь и
-- ложился НА БРОНЮ — десять её единиц уходило на то, что сопротивление
-- сняло бы даром. Порядок вызовов был правильный, а на глаз это
-- выглядело ровно как «сначала броня» (см. SB.Skills.ApplyResistance).
--
-- Значит, набрав достаточно резиста, слабый удар своей школы можно снять
-- целиком. Так и должно быть: это же обещает слово «устойчивость», и
-- собрать пятёрку против одной школы — отдельная работа из четырёх
-- источников.
--
-- ОТРИЦАТЕЛЬНЫЙ РЕЗИСТ — ЭТО УЯЗВИМОСТЬ, и она работает: канал эффекта
-- принимает минус везде, и запрещать его именно здесь было бы
-- произволом. «Уязвимость к огню» пишется как resistFire = -2 — ровно
-- так описаны «Проклятие стихий» и обратная сторона «Дубовой кожи».
--
-- ── ЛЕСТНИЦА ЗНАЧЕНИЙ ───────────────────────────────────────
--
-- Она короткая, и не от бедности фантазии. Запас здоровья здесь 3-9, а
-- удар снимает 2-4: двойка против школы — это уже половина обычного
-- удара, тройка — почти неуязвимость. Места на «слабый, средний,
-- сильный, очень сильный» тут просто нет, и растягивать лестницу вверх
-- значит ломать размен.
--
--   1  РАСА              вечно, одна школа, ничего не стоит
--   1  ЗЕЛЬЕ             гарантировано и без броска, но слабее
--                        заклинаний — этим и платит за надёжность
--   1  АУРА НА ГРУППУ    накрывает весь рейд и висит сотни ходов
--   2  ЛИЧНЫЙ ОБЕРЕГ     один союзник, несколько ходов
--   3  «Божественный щит» — единственное исключение, см. его врезку
--
-- Правило лестницы простое: ЧЕМ ШИРЕ И ДОЛЬШЕ, ТЕМ МЕНЬШЕ. Аура
-- паладина слабее личного оберега мага не потому, что паладин хуже, а
-- потому что аура работает на всех и весь бой.
--
-- СЛОЖЕНИЕ ИСТОЧНИКОВ НЕ ОГРАНИЧЕНО, и это осознанно: Отрекшийся под
-- аурой, оберегом и зельем наберёт против тьмы пятёрку и будет держать
-- любой теневой удар до пяти. Собрать четыре источника разом — отдельная
-- работа, которой не жалко такой награды. Если окажется, что жалко, —
-- потолок ставится одной строкой в SB.Skills.GetResistance.
-- ============================================================
SB.Data.RESIST_ALL   = "resistAll"
SB.Data.RESIST_MAGIC = "resistMagic"

--- Ключ личного сопротивления школе: "fire" → "resistFire".
local function KeyOf(typeID)
    return "resist" .. typeID:sub(1, 1):upper() .. typeID:sub(2)
end

-- Все ключи разом. По ним строятся расовые профили (Core/Database.lua) и
-- каналы эффектов (Core/ActiveEffects.lua); свой список в каждом из трёх
-- мест разъехался бы при добавлении восьмой школы.
--
-- Порядок — общий, магия, дальше школы по алфавиту: pairs по таблице
-- выше даёт каждый раз новый, а из этого списка строится порядок строк
-- в подсказке эффекта.
SB.Data.ResistKeys = { SB.Data.RESIST_ALL, SB.Data.RESIST_MAGIC }
do
    local names = {}
    for id in pairs(SB.Data.DamageTypes) do names[#names + 1] = id end
    table.sort(names)
    for _, id in ipairs(names) do
        -- Все школы, физическая тоже (см. врезку выше).
        SB.Data.DamageTypes[id].resistKey = KeyOf(id)
        SB.Data.ResistKeys[#SB.Data.ResistKeys + 1] = KeyOf(id)
    end
end

--- Подпись ключа для подсказок. Выводится из имени школы, а не пишется
--- второй раз: переименуй «Тьму» — и подпись поедет за ней сама.
function SB.Data.ResistLabel(key)
    if key == SB.Data.RESIST_ALL   then return "Сопротивление: весь урон" end
    if key == SB.Data.RESIST_MAGIC then return "Сопротивление: магия"     end
    for _, dt in pairs(SB.Data.DamageTypes) do
        if dt.resistKey == key then return "Сопротивление: " .. dt.name end
    end
    return key
end

--- Какие ключи сопротивления гасят урон этой школы.
---
--- УРОН БЕЗ ТИПА — ЧИСТЫЙ, И НЕ ГАСИТ ЕГО НИЧТО (см. SB.Data.PURE_DAMAGE).
--- Прежде такой удар получал общий резист — «оставить без защиты хуже»,
--- — и это было правило, которого игрок не видел: в карточке у
--- заклинания без типа не стояло ничего, а резист «ко всему» его
--- молча гасил. Теперь у отсутствия типа есть имя, и правило у него одно
--- и простое: чистый урон проходит сквозь любое сопротивление.
---
--- Доспех к сопротивлениям не относится и чистый урон по-прежнему гасит:
--- это расходуемый запас, а не устойчивость к школе (см. врезку выше).
--- @return table  список ключей (пустой — чистый урон)
function SB.Data.ResistKeysFor(typeID)
    local dt = SB.Data.DamageTypes[typeID or ""]
    if not dt then return {} end
    if not dt.magic then return { SB.Data.RESIST_ALL, dt.resistKey } end
    return { SB.Data.RESIST_ALL, SB.Data.RESIST_MAGIC, dt.resistKey }
end

-- ============================================================
-- ПРИБАВКА К УРОНУ — ТЕ ЖЕ ТРИ УРОВНЯ, ЗЕРКАЛЬНО
--
--   damage         — весь наносимый урон, какой бы школы он ни был;
--   damageMagic    — вся магия, но не сталь;
--   damage<Школа>  — одна школа.
--
-- КЛЮЧ «damage» ОСТАЛСЯ ПРЕЖНИМ, и это не небрежность. Он объявлен у
-- полусотни эффектов в библиотеке и читается пятью путями резолва;
-- переименовать его в damageAll ради красоты симметрии значило бы
-- переписать все пятьдесят и получить ровно ноль новой пользы. Роль у
-- него та же, что у resistAll: «всё сразу».
--
-- А ВОТ У ФИЗИЧЕСКОГО ЗДЕСЬ КЛЮЧ ЕСТЬ — в отличие от сопротивлений, и
-- на то есть причина. На защите физическому не нужен свой ключ, потому
-- что сопротивление стали в аддоне уже есть и называется доспехом. На
-- атаке никакого «доспеха наоборот» нет: «+1 к урону оружием» — обычная
-- боевая песнь, и выразить её было бы нечем.
--
-- СКЛАДЫВАЮТСЯ, как и сопротивления: «+1 всему урону» и «+2 огню» на
-- огненном шаре дают три. Разные источники — разные прибавки.
-- ============================================================
SB.Data.DAMAGE_ALL   = "damage"
SB.Data.DAMAGE_MAGIC = "damageMagic"

--- Ключ прибавки к одной школе: "fire" → "damageFire".
local function DmgKeyOf(typeID)
    return "damage" .. typeID:sub(1, 1):upper() .. typeID:sub(2)
end

-- НОВЫЕ ключи — без «damage»: тот уже объявлен и в каналах эффектов, и
-- в подписях, и второй раз его туда добавлять нечего.
SB.Data.DamageBonusKeys = { SB.Data.DAMAGE_MAGIC }
do
    local names = {}
    for id in pairs(SB.Data.DamageTypes) do names[#names + 1] = id end
    table.sort(names)
    for _, id in ipairs(names) do
        SB.Data.DamageTypes[id].damageKey = DmgKeyOf(id)
        SB.Data.DamageBonusKeys[#SB.Data.DamageBonusKeys + 1] = DmgKeyOf(id)
    end
end

--- Подпись ключа для подсказок. Выводится из имени школы — переименуй
--- «Тьму», и подпись поедет за ней сама.
function SB.Data.DamageBonusLabel(key)
    if key == SB.Data.DAMAGE_MAGIC then return "Урон: магия" end
    for _, dt in pairs(SB.Data.DamageTypes) do
        if dt.damageKey == key then return "Урон: " .. dt.name end
    end
    return key
end

--- Какие ключи прибавки работают на урон этой школы.
--- Неизвестная (или отсутствующая) школа получает только общий: тип
--- урона у своего заклинания игрок не пишет, и оставить такой удар вовсе
--- без прибавок было бы хуже, чем дать ему общую.
--- @return table  список ключей
function SB.Data.DamageKeysFor(typeID)
    local dt = SB.Data.DamageTypes[typeID or ""]
    if not dt then return { SB.Data.DAMAGE_ALL } end
    if not dt.magic then return { SB.Data.DAMAGE_ALL, dt.damageKey } end
    return { SB.Data.DAMAGE_ALL, SB.Data.DAMAGE_MAGIC, dt.damageKey }
end

-- ============================================================
-- ТИП УРОНА ЗАКЛИНАНИЯ
--
-- Возвращает ЗАПИСЬ ТИПА, а не строку: вызывающему всегда нужны и имя,
-- и цвет разом, и склеивать их из двух обращений незачем.
--
-- НЕТ ТИПА — ЗНАЧИТ ЧИСТЫЙ. Раньше здесь был nil и строка урона без
-- подписи: подставить «физический» значило бы соврать про каждый
-- самодельный огненный шар (своё заклинание игрок пишет сам, поля
-- damageType в нём нет). Но молчание врало иначе — резист «ко всему»
-- такой удар гасил, а в карточке об этом не было ни слова. Теперь у
-- отсутствия типа есть своё правило (его не гасит ни одно
-- сопротивление, см. ResistKeysFor) и своё имя, и игрок видит его там
-- же, где видит любой другой тип.
--
-- ОПЕЧАТКА В damageType ТОЖЕ ДАЁТ ЧИСТЫЙ: незнакомая школа — это
-- отсутствие школы, и правило у них обязано быть одним.
--
-- В SB.Data.DamageTypes чистого НЕТ намеренно: оттуда строятся ключи
-- сопротивлений и прибавок, а сопротивления чистому урону не бывает —
-- ключ под него был бы ключом, который ничего не гасит.
SB.Data.PURE_DAMAGE = { id = "pure", name = "Чистый", color = "FFFFFFFF",
                        magic = false, pure = true }

-- @return table|nil  запись из SB.Data.DamageTypes или SB.Data.PURE_DAMAGE
function SB.Data.GetDamageType(spell)
    if type(spell) == "string" then spell = SB.Data.Spells[spell] end
    if type(spell) ~= "table" then return nil end
    return SB.Data.DamageTypes[spell.damageType or ""] or SB.Data.PURE_DAMAGE
end

--- Текст в цвете типа. Пустой тип отдаёт текст нетронутым — так место
--- вызова не обрастает проверкой на nil.
function SB.Data.ColorByDamageType(dt, text)
    if not dt then return text end
    return "|c" .. dt.color .. text .. "|r"
end
