-- ============================================================
-- Core/Cooldowns.lua
-- ГЛОБАЛЬНЫЕ КУЛДАУНЫ — «не чаще, чем раз в N секунд».
--
-- ЗАЧЕМ. Всё, что игрок делает в аддоне, уходит в групповой канал: каст,
-- бросок, показ заклинания. Канал общий и узкий (ChatThrottleLib отдаёт
-- порядка 800 байт в секунду на клиента), и один суетливый человек с
-- зажатой кнопкой забивает его всей группе — чужие боевые пакеты встают
-- в очередь за его шестым подряд броском. Кулдаун здесь не игровая
-- механика, а предохранитель: он ограничивает ТЕМП, а не возможности.
--
-- ТРИ НЕЗАВИСИМЫХ СЧЁТЧИКА. Они меряют разные вещи и не должны мешать
-- друг другу:
--   TURN — действие в ход: каст, Короткий Отдых, пропуск хода. Работает
--          и в свободной игре, где очереди ходов нет вовсе, и там он
--          единственная защита от спама способностями;
--   ROLL — свободный бросок (проверка навыка, ручная атака/защита) и
--          показ заклинания группе. Ход не тратят, поэтому TURN их не
--          ловит, а в канал они уходят точно так же;
--   GM   — объявления Ведущего, меняющие состояние ВСЕЙ сцены: Долгий
--          Отдых и переключение пошагового режима. Каждое такое
--          объявление — рассылка всем и перерисовка у всех.
--
-- ПАМЯТЬ, А НЕ СОХРАНЁНКИ. Кулдаун в шесть секунд не переживает
-- /reload — но и не должен: сама перезагрузка интерфейса занимает
-- дольше, обойти ограничение ею невозможно.
-- ============================================================
local addonName, SB = ...
SB.Cooldowns = SB.Cooldowns or {}
local CD = SB.Cooldowns

CD.TURN = "turn"
CD.ROLL = "roll"
CD.GM   = "gm"

-- Длительности разведены: счётчики независимы по смыслу, и мерить их
-- одним числом больше нельзя.
--
-- GM КОРОЧЕ ОСТАЛЬНЫХ ВТРОЕ. Долгий Отдых и переключение пошагового
-- режима — не спам, а разметка сцены: Ведущий жмёт их по разу на
-- эпизод, и шесть секунд ожидания на переключении режима туда-обратно
-- он ждал зря. Предохранитель при этом остаётся: пары секунд хватает,
-- чтобы рассылка одного объявления успела уйти до следующего.
local DURATION = {
    [CD.TURN] = 6,
    [CD.ROLL] = 6,
    [CD.GM]   = 2,
}

-- Сообщение об отказе — своё на каждый счётчик: «слишком часто» без
-- уточнения, что именно слишком часто, игрок читает как поломку.
local MESSAGE = {
    [CD.TURN] = "Вы только что действовали. Следующее действие через %d сек.",
    [CD.ROLL] = "Слишком часто. Следующий бросок через %d сек.",
    [CD.GM]   = "Слишком часто. Следующее объявление через %d сек.",
}

local readyAt = {}

-- ============================================================
-- ТЕМП ДЕЙСТВИЯ ЖИВЁТ ТОЛЬКО В СВОБОДНОЙ ИГРЕ
--
-- Шесть секунд между действиями заводились как предохранитель от спама
-- там, где сдерживать игрока больше нечем. В ПОШАГОВОМ РЕЖИМЕ сдерживает
-- очередь: походил — жди своего следующего хода, и никакой кнопкой этого
-- не обойти. Второй предохранитель поверх первого не защищает ни от
-- чего, зато мешает: игрок, дождавшийся своего хода, упирался в «вы
-- только что действовали» и терял ход, который очередь ему выдала.
--
-- Хуже всего это ловилось на автопропуске по передвижению: ход
-- закрывался с задержкой в шесть секунд, а то и не закрывался вовсе.
--
-- ТОЛЬКО TURN. ROLL остаётся включённым и в пошаговом режиме: свободный
-- бросок и показ заклинания ХОДА НЕ ТРАТЯТ, очередь их не видит, и
-- зажатая кнопка проверки навыка забивает канал ровно так же, как в
-- свободной игре. GM — тем более: объявления Ведущего к очереди
-- отношения не имеют.
--
-- Правится в Remaining, а не в Check: через неё же считают Ready и
-- полоска отката на панели способностей, и разойдись они — кнопка
-- гасла бы на кулдауне, которого нет.
-- ============================================================

--- Сколько секунд осталось (0 — готово).
function CD.Remaining(key)
    if key == CD.TURN and SB.TurnOrder and SB.TurnOrder.IsActive
       and SB.TurnOrder.IsActive() then
        return 0
    end
    local t = readyAt[key]
    if not t then return 0 end
    local left = t - GetTime()
    return (left > 0) and left or 0
end

function CD.Ready(key)
    return CD.Remaining(key) <= 0
end

--- Взвести счётчик. Зовётся ПОСЛЕ того, как действие состоялось, а не
--- перед: отказ по любой другой причине (нет ресурса, цель далеко) не
--- должен запирать игрока на шесть секунд.
function CD.Start(key)
    readyAt[key] = GetTime() + (DURATION[key] or 6)
end

--- Проверка перед действием: печатает, сколько ждать, и возвращает
--- false. Зеркало SB.Movement.CheckCanAct и SB.TurnOrder.CheckCanAct —
--- вызывающему хватает одной строки.
function CD.Check(key)
    local left = CD.Remaining(key)
    if left <= 0 then return true end
    -- Округляем ВВЕРХ: «через 0 сек» при остатке в полсекунды выглядит
    -- как обман, а лишняя секунда в подписи никого не задержит.
    print(SB.Theme.MSG_BAD .. "[Spellbreaker]: " ..
        string.format(MESSAGE[key] or "Слишком часто. Подождите %d сек.",
            math.ceil(left)) .. "|r")
    return false
end
