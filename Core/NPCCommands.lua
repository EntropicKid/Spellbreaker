--
-- ОТКУДА ЭТО. Перенесено из отдельного аддона N'PeeSix (автор Rissy):
-- он умел то, чего Spellbreaker не умел вовсе — двигать саму тушку на
-- сервере: менять облик, размер, оружие, отношение, проигрывать эмоции,
-- говорить от её лица. Держать это отдельным аддоном было неудобно
-- ровно потому, что половина работы Ведущего со сценой уже жила здесь:
-- НПС заводятся в библиотеке, по ним считается размен, на них висят
-- эффекты — а «сделай его большим и посади за стол» приходилось делать
-- из другого меню.
--
-- ЧТО ЗДЕСЬ, А ЧТО В UI. Здесь — только ДАННЫЕ и ОТПРАВКА: списки
-- пресетов и единственная функция, которая шлёт команду серверу. Меню,
-- кнопки и окна — в UI/NPCControl.lua. Разделение то же, что у всего
-- остального в аддоне, и по той же причине: данные проверяются
-- прогоном, интерфейс — нет.
--
-- ============================================================
-- ЭТО НЕ МЕХАНИКА АДДОНА, А КОМАНДЫ СЕРВЕРУ
--
-- Всё в этом файле уходит строкой в чат («.npc set mod 12345») и
-- исполняется эмулятором. Отсюда два следствия, о которых надо помнить.
--
-- ПЕРВОЕ: РАБОТАЕТ ТОЛЬКО У ТОГО, У КОГО ЕСТЬ ПРАВА. Обычному игроку
-- сервер откажет, и аддон об этом не узнает — ответ приходит системным
-- сообщением, а не в наш код.
--
-- УГАДЫВАТЬ ЭТИ ПРАВА АДДОН НЕ ПЫТАЕТСЯ. Была попытка: кнопку показывали
-- только лидеру группы. Вышло хуже, чем ничего — право слать «.npc»
-- выдаёт сервер, к лидерству в группе оно не привязано никак, и Ведущий,
-- сидящий в рейде помощником, терял кнопку без всякой причины. Отказ от
-- сервера приходит внятной строкой и объясняет дело лучше, чем
-- исчезнувшая кнопка.
--
-- ВТОРОЕ: ЦЕЛЬ — ТО, ЧТО В ТАРГЕТЕ, И БОЛЬШЕ НИЧЕГО. Команда не несёт
-- в себе GUID: сервер применит её к тому, кто выделен В МОМЕНТ ЕЁ
-- ПОЛУЧЕНИЯ. Поэтому перед отправкой проверяем, что в таргете
-- действительно существо, а длинные последовательности (речь по частям)
-- шлются с задержкой и рвутся при смене цели.
-- ============================================================
local addonName, SB = ...

SB.NPCCommands = SB.NPCCommands or {}

--- Отправить серверную команду.
---
--- ОДНА ТОЧКА НА ВСЕ КОМАНДЫ, и это не формальность. В исходном аддоне
--- SendChatMessage стоял в сотне мест по одному на пункт меню; добавить
--- к ним общую проверку (есть ли цель, тот ли это, кто мы думаем) было
--- негде. Здесь она одна.
---
--- ШЛЁМ ШЁПОТОМ САМОМУ СЕБЕ. Так эмулятор принимает команды, не
--- засоряя ими чат сцены: строка видна только отправителю.
--- @param cmd string  команда целиком, вместе с точкой
--- @return boolean  ушла ли команда
function SB.NPCCommands.Send(cmd)
    if type(cmd) ~= "string" or cmd == "" then return false end
    local me = UnitName("player")
    if not me then return false end
    SendChatMessage(cmd, "WHISPER", nil, me)
    return true
end

--- То же, но с проверкой, что в таргете существо.
---
--- Проверяем ЗДЕСЬ, а не в каждом пункте меню: команда без цели уходит
--- в пустоту молча, и Ведущий узнаёт об этом, только не увидев
--- результата.
function SB.NPCCommands.SendToTarget(cmd)
    if not UnitExists("target") or UnitIsPlayer("target") then
        print(SB.Theme.MSG_TAG .. "[Spellbreaker]|r: " .. SB.Theme.MSG_BAD ..
            "В цели нет существа — команда не отправлена.|r")
        return false
    end
    return SB.NPCCommands.Send(cmd)
end

-- ============================================================
-- ДЕЛЕНИЕ ДЛИННОЙ РЕПЛИКИ
--
-- Сервер принимает строку до 255 байт вместе с командой, и длинная
-- реплика без деления просто обрезается на полуслове. Делим ПО СЛОВАМ
-- со знаками препинания — так шов приходится на паузу, а не на середину
-- слова.
--
-- СЧИТАЕМ БАЙТЫ, А НЕ СИМВОЛЫ, и это важно именно здесь: кириллица в
-- UTF-8 занимает два байта на букву, и «255 символов» означало бы вдвое
-- больший пакет, который сервер обрежет сам — ровно посреди буквы.
-- ============================================================
function SB.NPCCommands.SplitByWords(message, maxBytes)
    local chunks, cur = {}, ""
    for word in message:gmatch("%S+[.,;:!?]?%s?") do
        if #cur + #word <= maxBytes then
            cur = cur .. word
        else
            if #cur > 0 then chunks[#chunks + 1] = cur end
            -- Слово длиннее целого куска (ссылка, набор символов) режем
            -- как есть: иначе цикл встал бы навсегда.
            while #word > maxBytes do
                chunks[#chunks + 1] = word:sub(1, maxBytes)
                word = word:sub(maxBytes + 1)
            end
            cur = word
        end
    end
    if #cur > 0 then chunks[#chunks + 1] = cur end
    return chunks
end

