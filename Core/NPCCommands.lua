-- ============================================================
-- DISPLAY ID ИЗ ОТВЕТА СЕРВЕРА
--
-- «.npc info» печатает про выделенную тушку системное сообщение, в
-- котором среди прочего есть её DisplayID. Он нужен, чтобы принять
-- ЭТОТ ЖЕ облик самому («.mor <id>») — обычный приём Ведущего: взял
-- облик стражника, отыграл сцену, вернулся.
--
-- ЛОВИМ СВОИМ ФРЕЙМОМ, А НЕ ПОДМЕНОЙ ChatFrame_OnEvent. В исходном
-- аддоне эта функция Blizzard переопределялась целиком, с сохранением
-- ссылки на прежнюю: пока такой аддон один, всё работает, но второй
-- такой же перезапишет первого, а третий — обоих, и порядок загрузки
-- начнёт решать, чей чат уцелеет. Обычная подписка на CHAT_MSG_SYSTEM
-- делает ровно то же и ничего чужого не трогает.
-- ============================================================
local pendingProbe = nil    -- функция-получатель, пока ждём ответ

local sysWatcher = CreateFrame("Frame")
sysWatcher:RegisterEvent("CHAT_MSG_SYSTEM")
sysWatcher:SetScript("OnEvent", function(_, _, msg)
    if not pendingProbe or type(msg) ~= "string" then return end
    local id = msg:match("DisplayID:%s*(%d+)")
    if not id then return end
    local cb = pendingProbe
    pendingProbe = nil
    cb(tonumber(id))
end)

--- Спросить у сервера DisplayID выделенного существа.
---
--- ОЖИДАНИЕ ОБРЫВАЕТСЯ ПО ТАЙМАУТУ. Ответа может не быть вовсе — нет
--- прав, нет цели, другой формат сообщения, — и оставленный навсегда
--- обработчик поймал бы чужой DisplayID из следующего «.npc info» через
--- полчаса и молча применил его.
--- @param callback function(displayID)
function SB.NPCCommands.ProbeDisplayID(callback)
    if type(callback) ~= "function" then return end
    if not SB.NPCCommands.SendToTarget(".npc info") then return end
    pendingProbe = callback
    C_Timer.After(3, function()
        if pendingProbe == callback then
            pendingProbe = nil
            print(SB.Theme.MSG_TAG .. "[Spellbreaker]|r: " .. SB.Theme.MSG_BAD ..
                "Сервер не ответил на «.npc info» — облик не определён.|r")
        end
    end)
end
