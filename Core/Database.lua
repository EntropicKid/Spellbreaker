-- ============================================================
-- КАНОНИЧЕСКОЕ ИМЯ КЛАССА
--
-- UnitClass() отдаёт имя класса В РОДЕ ПЕРСОНАЖА: у женского
-- Разбойника это «Разбойница», у Жреца — «Жрица», у Охотника —
-- «Охотница». Все таблицы аддона (SB.Data.Classes, NonCasterClasses,
-- ClassResourceNames, ClassProfiles, STARTER_SPELLS, spell.class)
-- ключуются мужской формой — и для женских персонажей КАЖДЫЙ такой
-- поиск молча возвращал nil.
--
-- Последствия были куда шире «не работает профиль класса»:
--   • NonCasterClasses[«Охотница»] = nil → некастер считался кастером,
--     получал Ману вместо Фокуса и ранг по предметам вместо уровня;
--   • STARTER_SPELLS[«Жрица»] = nil → на первом запуске не выдавалось
--     ни одного стартового заклинания;
--   • ClassProfiles[«Разбойница»] = nil → нулевой профиль.
--
-- Поэтому имя класса берётся НЕ из локализованной строки, а из
-- английского токена (второй возврат UnitClass: "ROGUE", "PRIEST", …) —
-- он не зависит ни от рода, ни от языка клиента.
-- ============================================================
