-- ============================================================
-- СВОИ И ЧУЖИЕ (список друзей)
--
-- ЗАЧЕМ. Площадное заклинание не выбирает целей: бросок уходит группе, и
-- каждый получатель сам решает, задело ли его (см. Core/Logic/Aoe.lua).
-- До сих пор он решал это только по радиусу — то есть огненный шар
-- одинаково накрывал врага и союзника, стоящих рядом, а групповое
-- лечение одинаково поднимало обоих. На сцене «стенка на стенку» это
-- означало, что площадь применять нельзя вообще.
--
-- ОТМЕЧАЕТ ЗАКЛИНАТЕЛЬ, И РЕШАЕТ ТОЖЕ ОН. Список — это «по кому я не
-- бью», а не «от кого мне не прилетает»: галочка защищает того, на ком
-- она стоит, от МОЕЙ площади.
--   • мои атаки и дебаффы моих друзей не задевают;
--   • моё площадное лечение и баффы достаются ТОЛЬКО им.
--
-- Поэтому список едет вместе с залпом (поле fr, см. SB.Net.SendAoeAttack)
-- и в него попадают только те, кто сейчас в группе: до остальных площадь
-- всё равно не доставляется. Проверку делает получатель, ДО ответа
-- отправителю, — значит на залп по своим не уходит ни одного ответного
-- пакета (см. FriendIgnoresAoe в Core/Logic/Aoe.lua).
--
-- ВАЖНОЕ СЛЕДСТВИЕ, О КОТОРОМ НАДО ЗНАТЬ ЗА СТОЛОМ: пока лекарь никого
-- не отметил, его площадное лечение не достаётся НИКОМУ, кроме него
-- самого. Это не сбой, а прямое следствие правила «добро — только
-- своим»: перед сценой лекарь отмечает тех, кого лечит.
--
-- СПИСОК АККАУНТНЫЙ. Стороны конфликта переживают и /reload, и смену
-- персонажа: событие идёт вечер, а перепроставлять галочки после каждого
-- вылета — ровно то, чего мы избегаем.
-- ============================================================

--- @return table  [имя] = true. Живая таблица из сохранёнок.
function SB.Data.GetFriends()
    local db = SpellbreakerAccountDB
    if not db then return {} end
    db.friends = db.friends or {}
    return db.friends
end

--- Отмечен ли игрок своим.
--- САМ СЕБЕ ВСЕГДА ДРУГ: собственная площадь и так не бьёт по себе (см.
--- AoeHitsSelf), а собственное лечение обязано доходить независимо от
--- того, отметил ли игрок сам себя в списке.
function SB.Data.IsFriend(name)
    if not name or name == "" then return false end
    if name == UnitName("player") then return true end
    return SB.Data.GetFriends()[name] == true
end

--- Отметить/снять. Снятие пишет nil, а не false: список ходит в
--- сохранёнки, и «false» на полсотни имён — это полсотни строк мусора,
--- которые ничего не значат.
function SB.Data.SetFriend(name, isFriend)
    if not name or name == "" then return end
    local friends = SB.Data.GetFriends()
    friends[name] = isFriend and true or nil
end

--- Мои друзья, которые СЕЙЧАС В ГРУППЕ, — массивом для отправки вместе
--- с площадным заклинанием.
---
--- Фильтр по группе не украшение: площадь доставляется аддон-сообщением,
--- то есть до тех, кого в группе нет, она не дойдёт в любом случае, — а
--- список за годы игры набирается длинный, и гонять его целиком в каждом
--- залпе значит платить за имена, которые никому не нужны. Себя не
--- включаем: своя площадь по себе не бьёт и без списка.
--- @return string[]
function SB.Data.GetGroupFriends()
    local out = {}
    if not IsInGroup() then return out end
    local friends = SB.Data.GetFriends()
    if not next(friends) then return out end

    local prefix = IsInRaid() and "raid" or "party"
    local n      = IsInRaid() and 40 or 4
    local me     = UnitName("player")
    for i = 1, n do
        local unit = prefix .. i
        if UnitExists(unit) and UnitIsPlayer(unit) then
            local name = UnitName(unit)
            if name and name ~= me and friends[name] then out[#out + 1] = name end
        end
    end
    return out
end

