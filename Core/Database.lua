-- ============================================================
-- ПРОФИЛИ КЛАССОВ — сильные и слабые стороны
--
-- До этой таблицы все классы считались по ОДНИМ И ТЕМ ЖЕ формулам:
-- одинаковое здоровье, одинаковый ресурс, одинаковые броски. Отличий
-- было ровно два — чем восполняется ресурс (Core/ClassMechanics.lua)
-- и от какой характеристики скейлятся заклинания. То есть на бумаге
-- классы разные, а в цифрах — один и тот же персонаж в разных плащах.
--
-- Профиль сдвигает четыре величины. Числа маленькие НАМЕРЕННО: запас
-- здоровья на максимуме — 9, ресурса — 3 у некастеров, так что +2 к
-- здоровью или +4 к броску это уже очень много.
--
--   health   — сдвиг максимума здоровья (итог зажимается снизу двойкой:
--              на 1-2 уровнях база и так равна 2, и минус там означал бы
--              «один удар — труп» с самого старта)
--   resource — сдвиг максимума ресурса каста (Мана у кастеров,
--              Ярость/Энергия/... у некастеров)
--   attack   — плоский сдвиг ВСЕХ бросков атаки/каста/лечения
--   defense  — плоский сдвиг бросков защиты (ПвП-уворот)
--
-- ВАЖНО про сравнение кастеров и некастеров: складывать их профили
-- «в лоб» нельзя. Урон кастера растёт с вложенной маной (до 4 + скейлинг),
-- у некастера он фиксирован (1 + скейлинг), зато некастер восполняет
-- ресурс прямо в бою. Поэтому у некастеров профили в среднем прочнее —
-- это компенсация, а не перекос. Балансировать имеет смысл ВНУТРИ
-- каждой из двух групп.
-- ============================================================
SB.Data.ClassProfiles = {
    -- ── Кастеры ──────────────────────────────────────────────
    -- Маг: эталонная «стеклянная пушка». Больше всех заклинаний и
    -- лучший бросок атаки, но в ближнем бою умирает мгновенно.
    ["Маг"]                = { health = -1, resource =  2, attack =  4, defense = -4, prepared = 2 },
    -- Чернокнижник: почти маг, но платит собственным здоровьем и
    -- потому чуть осторожнее в размене.
    ["Чернокнижник"]       = { health = 1, resource =  -1, attack =  0, defense = 2, prepared = 1, restHeal = -1 },
    -- Жрец: слабейший в атаке кастер — его сила в лечении и
    -- «Милосердии», а не в уроне.
    ["Жрец"]               = { health = -1, resource =  0, attack = -3, defense =  3, restHeal = 1, prepared = 1 },
    -- Шаман: универсал без перекосов, ровно по нулям во всём.
    ["Шаман"]              = { health =  0, resource =  0, attack =  1, defense =  1, skillPoints = 1, restHeal = 1 },
    -- Друид: живучий природник, но бьёт неточно.
    ["Друид"]              = { health =  0, resource = 2, attack = 0, defense =  0, restHeal = 1 },
    -- Паладин: латная скала. Лучшая защита среди кастеров, но
    -- заклинаний мало и атака слабая.
    ["Паладин"]            = { health =  3, resource = -2, attack = -3, defense =  2 },

    -- ── Некастеры ────────────────────────────────────────────
    -- Воин: максимум мяса, и мясо это рабочее — Ярость копится с
    -- ПОЛУЧЕННОГО урона (см. Core/ClassMechanics.lua), так что запас
