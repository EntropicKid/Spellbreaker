-- ============================================================
-- «МЯГКИЕ» РЫЧАГИ — то, чем отличаются РАСЫ и (дополнительно) КЛАССЫ
--
-- Отдельный набор от attack/defense специально: на бросок и так уже
-- влияют ранг, уровень, характеристики, вложенный ресурс, профиль
-- класса, навыки и висящие эффекты. Ещё один слагаемый там ничего не
-- выражает — он просто растворяется в сумме. Поэтому расы двигают то,
-- что к броску не прибавляется вовсе:
--
--   prepared     +N к лимиту подготовленных заклинаний (на всех рангах)
--   rollFloor    нижняя грань кубика: вместо 1-100 бросок идёт N-100.
--                Это не прибавка к результату, а срез самых неудачных
--                исходов: средний бросок выходит выше, а провалы реже.
--   health       +N к максимуму здоровья
--   resource     +N к максимуму ресурса каста
--   armor        +N единиц брони (без требования к навыку)
--   skillPoints  +N очков навыков к распределению
--   attrPoints   +N очков ХАРАКТЕРИСТИК к распределению. Вдесятеро
--                весомее очка навыка: база всего 5 (плюс одно за каждые
--                пять уровней), характеристика тянет за собой все свои
--                навыки, и она же кормит скейлинг заклинаний. Единица
--                здесь — это пятая часть стартового персонажа
--   moveCap      +N метров передвижения за ход (см. Core/Movement.lua)
--
-- ЗДЕСЬ БЫЛИ restHeal И restCharges — оба про Короткий Отдых, которого
-- больше нет. Сняты вместе с ним, а не оставлены «на всякий случай»:
-- незнакомый ключ профиля молча не читается никем, и мёртвое поле в
-- данных однажды прочтут как живое. Держали их восемь классов и две
-- расы; см. запись о сносе в README.
--
