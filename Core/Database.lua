function SB.Data.GetClassProfile(className)
    className = className or (SB.PlayerModel and SB.PlayerModel.GetClass())
    return SB.Data.ClassProfiles[className] or EMPTY_PROFILE
end

--- Принадлежит ли ЗАКЛИНАНИЕ кастерскому классу. Именно от этого, а не
