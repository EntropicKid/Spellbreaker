local EMPTY_SOFT = {}

--- Расовый профиль текущего персонажа (или пустой для незнакомой расы).
function SB.Data.GetRaceProfile(unit)
    local _, token = UnitRace(unit or "player")
    if not token then return EMPTY_SOFT end
    return SB.Data.RaceProfiles[token]
        or SB.Data.RaceProfiles[RACE_ALIASES[token] or ""]
        or EMPTY_SOFT
end

--- Суммарный «мягкий» бонус: раса + класс. Оба набора читаются одним
--- вызовом, чтобы вызывающему коду не приходилось складывать их руками
--- в восьми местах.
--- @param key string  один из SOFT_KEYS
function SB.Data.GetSoftBonus(key)
    local race  = SB.Data.GetRaceProfile()
    local class = SB.Data.GetClassProfile()
    return (tonumber(race[key]) or 0) + (tonumber(class[key]) or 0)
end

local EMPTY_PROFILE = { health = 0, resource = 0, attack = 0, defense = 0 }

--- Профиль класса. Незнакомый класс получает нули, а не nil —
--- вызывающему коду не нужно каждый раз проверять наличие.
function SB.Data.GetClassProfile(className)
    className = className or (SB.PlayerModel and SB.PlayerModel.GetClass())
    return SB.Data.ClassProfiles[className] or EMPTY_PROFILE
end

