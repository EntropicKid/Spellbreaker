--- Что заклинание требует надеть (или nil).
---
--- НЕИЗВЕСТНЫЙ ВИД МОЛЧА СНИМАЕТ ТРЕБОВАНИЕ, а не запрещает каст. Это
--- намеренно: опечатка в requirement у кастомного заклинания Ведущего
--- иначе превратила бы его в невыполнимое, и разбираться пришлось бы в
--- сцене. Проверка на опечатки живёт в прогоне, где ей и место.
--- @return string|nil  ключ из SB.Data.EquipRequirements
function SB.Data.GetEquipRequirement(spell)
    if type(spell) ~= "table" then return nil end
    -- Явное поле сильнее дескриптора, в том числе явным отказом.
    if spell.requirement ~= nil then
        return SB.Data.EquipRequirements[spell.requirement] and spell.requirement or nil
    end
    return SB.Data.KeyRequirements[spell.key]
end

-- ============================================================
-- СЕМЕЙСТВА ЭФФЕКТОВ (family)
--
-- Облики, печати, стойки и ауры — это ВЫБОР, а не набор. Медведем и
-- совой одновременно не побудешь, две печати на одном клинке не горят;
-- но пока это держалось на честном слове, панель эффектов у друида к
-- середине сцены превращалась в список всех его форм разом.
--
-- Семейство — общая строка в описании нескольких ЭФФЕКТОВ. Новый эффект
-- семейства сбрасывает предыдущий, какой бы из них ни висел:
--
--   AddEffect({ id = "eff_circle_of_paw",
--       effect = { kind = "buff", family = "Облик", mods = { ... } } })
--   AddEffect({ id = "eff_circle_of_beak",
--       effect = { kind = "buff", family = "Облик", mods = { ... } } })
--
-- ПОЛЕ ИМЕННО У ЭФФЕКТА, А НЕ У ЗАКЛИНАНИЯ — и это не мелочь, а весь
-- смысл. Конфликтует то, что ВИСИТ, независимо от того, откуда оно
-- взялось: свой каст, чужой бафф по сети, выдача Ведущим из панели,
-- восстановление после /reload. Объяви семейство у заклинания — и облик,
-- выданный Ведущим напрямую, не сменил бы уже висящий, потому что
-- заклинания в этом пути нет вовсе.
--
-- По той же причине ПРОВЕРКА ОДНА, в SB.ActiveEffects.Add: через неё
-- проходит всё, что вешается на персонажа. Ставить её в каждом пути
-- значило бы однажды забыть один — и получить двух медведей.
-- ============================================================

--- Семейство эффекта (или nil).
--- @return string|nil
function SB.Data.GetFamily(spellID)
    if not spellID then return nil end
    local sp = SB.Data.Spells[spellID]
    if not sp then return nil end

    -- Основное место — внутри описания эффекта, рядом с kind и mods.
    local def = sp.effect
    local own = (type(def) == "table") and def.family or nil
    -- Запасное — поле верхнего уровня: у контейнера-пустышки блока
    -- effect может не быть вовсе (чистая метка вроде «под маскировкой»),
    -- а в семейство он при этом входить может.
    if type(own) ~= "string" or own == "" then own = sp.family end

    if type(own) == "string" and own ~= "" then return own end
    return nil
end

--- Зарегистрировать заклинание в общем реестре.
--- @param spellData table  Таблица с полями id, name, class, level, …
function SB.Database.AddSpell(spellData)
    SB.Data.Spells[spellData.id] = spellData
    -- Контейнеры сами потоками не бывают: держатель для держателя
    -- породил бы бесконечную цепочку при перезагрузке кастомных данных.
    if spellData.channel and not spellData.isContainer then
        RegisterChannelHolder(spellData)
    end
end

