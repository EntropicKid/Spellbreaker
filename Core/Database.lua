--- Каноническое (мужское) имя класса юнита — то, которым ключуются
--- все таблицы аддона.
--- @param unit string|nil  по умолчанию "player"
--- @return string
function SB.Data.CanonicalClass(unit)
    unit = unit or "player"
    local localized, token = UnitClass(unit)
    -- Фолбэк на локализованное имя: незнакомый токен лучше показать
    -- как есть, чем отдать nil и уронить вызывающего.
    return (token and SB.Data.ClassByToken[token]) or localized or "?"
end

-- ============================================================
-- ОПРЕДЕЛЕНИЕ РЕАЛМА
--
-- Проект Aviana — это ДВА разных реалма: Origins (кап 25) и
-- Sanctuary (кап 100). Раньше здесь стояло точное сравнение
-- GetRealmName() == "Aviana", и оно не срабатывало никогда: клиент
-- отдаёт имя реалма то как "Origins", то как "Aviana - Origins",
-- то как "AvianaOrigins" (нормализованная форма без пробелов и
-- дефисов) — в зависимости от того, какую строку прописал сервер.
-- Из-за этого Sanctuary молча уезжал в дефолт Origins, и ни
-- растяжка прогрессии, ни скрытие классов не работали.
--
-- Поэтому реалм определяется не равенством строк, а поиском
-- КЛЮЧЕВОГО СЛОВА в нормализованном (нижний регистр, без пробелов,
-- дефисов, апострофов и точек) имени. Проверяются все источники
-- имени, какие даёт клиент, — какой-нибудь из них да сработает.
-- ============================================================
SB.Data.REFERENCE_MAX_LEVEL = 25

-- Порядок важен: первое совпадение выигрывает. "aviana" стоит
-- последней — это имя ПРОЕКТА, а не реалма, и встречается в обеих
-- строках ("Aviana - Origins", "Aviana - Sanctuary"), поэтому
-- служит только фолбэком, когда конкретный реалм не опознан.
--
-- Поля maxMastery / masteryByLevel описывают прогрессию РАНГОВ:
--   maxMastery     — сколько первых элементов SB.Data.Masteries доступно
--                    на реалме (3 = до Эксперта, 5 = до Героя).
--   masteryByLevel — собственная таблица порогов ранга по уровню для
--                    НЕКАСТЕРОВ (у кастеров ранг всегда от предмета).
--                    Реалм без неё пользуется общими порогами по
--                    эталонной шкале — см. SB.Data.GetMasteryForLevel.
SB.Data.RealmProfiles = {
    { id = "Sanctuary", match = "sanctuary", maxLevel = 100, restrictClasses = false,
      maxMastery = 5,
      masteryByLevel = {
          { 10, "Неофит" }, { 35, "Адепт" }, { 60, "Эксперт" },
          { 75, "Мастер" }, { 90, "Герой"  },
      } },
    { id = "Origins",   match = "origins",   maxLevel = 25,  restrictClasses = true, maxMastery = 3 },
    { id = "Origins",   match = "aviana",    maxLevel = 25,  restrictClasses = true, maxMastery = 3 },
}

-- Профиль для реалма, который не опознан ни по одному ключевому
-- слову: ведёт себя как Origins по прогрессии, но НЕ режет классы —
-- скрывать половину библиотеки на незнакомом сервере хуже, чем
-- показать лишнее.
local UNKNOWN_REALM = { id = "?", maxLevel = SB.Data.REFERENCE_MAX_LEVEL, restrictClasses = false,
                        maxMastery = SB.Data.BASE_MASTERY_COUNT }

local function Normalize(s)
    if type(s) ~= "string" then return nil end
    s = s:lower():gsub("[%s%-_'%.]", "")
    return (s ~= "") and s or nil
end

--- Все варианты имени текущего реалма, какие может отдать клиент.
--- @return string[]  сырые строки (для вывода в отладке)
function SB.Data.GetRealmNames()
    local out, seen = {}, {}
    local function add(v)
        if type(v) == "string" and v ~= "" and not seen[v] then
            seen[v] = true
            table.insert(out, v)
        end
    end
    if GetRealmName then add(GetRealmName()) end
    if GetNormalizedRealmName then add(GetNormalizedRealmName()) end
    if UnitFullName then
        local _, realm = UnitFullName("player")
        add(realm)
    end
    return out
end

-- Кэш: имя реалма за сессию не меняется, а GetRealm() дёргается из
-- каждой формулы очков. nil = ещё не считали.
local resolvedRealm = nil

--- Профиль текущего реалма: { id, maxLevel, restrictClasses }.
--- Ручное переопределение — SpellbreakerAccountDB.realmOverride
--- ("Origins" / "Sanctuary"): страховка на случай, если сервер
--- назовёт реалм как-то совсем неожиданно.
function SB.Data.GetRealm()
    if resolvedRealm then return resolvedRealm end

    local found = nil

    local override = Normalize(SpellbreakerAccountDB and SpellbreakerAccountDB.realmOverride)
    if override then
        for _, p in ipairs(SB.Data.RealmProfiles) do
            if Normalize(p.id) == override then found = p break end
        end
    end

    if not found then
        for _, raw in ipairs(SB.Data.GetRealmNames()) do
            local norm = Normalize(raw)
            if norm then
                for _, p in ipairs(SB.Data.RealmProfiles) do
                    if norm:find(p.match, 1, true) then found = p break end
                end
            end
            if found then break end
        end
    end

    found = found or UNKNOWN_REALM

    -- Кэшируем только после загрузки настроек: до неё не виден
    -- realmOverride, и закэшированный результат оказался бы неверным.
    if SpellbreakerAccountDB then resolvedRealm = found end
    return found
end

--- Сбросить кэш определения реалма (после смены realmOverride).
function SB.Data.ResetRealmCache()
    resolvedRealm = nil
end

-- ── Ограничение классов по серверу ───────────────────────────
-- На Origins классы Друид/Монах/Охотник на демонов/Рыцарь смерти
-- отсутствуют как игровые — для остальных персонажей они скрываются
-- из библиотеки и недоступны для подготовки. Игрок, который
-- механически играет за один из этих классов, продолжает видеть и
-- готовить заклинания своего класса как обычно.
SB.Data.HiddenClassesOnOrigins = {
    ["Друид"]              = true,
    ["Монах"]              = true,
    ["Охотник на демонов"] = true,
    ["Рыцарь смерти"]      = true,
}

--- true, если на текущем реалме действует ограничение классов.
--- Имя историческое (осталось от точного сравнения с "Aviana") —
--- смысл теперь «реалм с урезанным списком классов».
function SB.Data.IsOriginsRealm()
    return SB.Data.GetRealm().restrictClasses == true
end

-- ============================================================
-- ПРОГРЕССИЯ ПО РЕАЛМАМ
--
-- Все формулы очков (атрибуты/навыки) и все таблицы порогов по
-- уровню (здоровье, бонус к броску, ранг некастеров — см.
-- Core/PlayerModel.lua) откалиброваны под максимальный уровень
-- REFERENCE_MAX_LEVEL = 25 (реалм Origins). На реалме с другим
-- максимальным уровнем (Sanctuary, кап 100) та же итоговая
-- прогрессия должна раскрываться к КОНЦУ прокачки, а не к 25-му
-- уровню — то есть растянуться пропорционально.
--
-- Механизм — один: текущий уровень персонажа переводится в
-- "уровень по эталонной шкале 1-25" через ToReferenceLevel, и это
-- значение подставляется в ОРИГИНАЛЬНЫЕ, НЕТРОНУТЫЕ формулы/таблицы.
-- Так на Origins (maxLevel = REFERENCE_MAX_LEVEL) число не меняется
-- вообще, а вся стретч-логика живёт в одном месте.
-- ============================================================

--- Максимальный уровень персонажа на текущем реалме.
function SB.Data.GetMaxCharacterLevel()
    return SB.Data.GetRealm().maxLevel or SB.Data.REFERENCE_MAX_LEVEL
end

--- Переводит реальный уровень персонажа в "уровень по эталонной шкале
--- 1-25", на которой откалиброваны формулы очков и таблицы порогов.
--- На Origins (maxLevel = 25) — тождественная функция.
--- @return number  может быть дробным — сравнения/формулы ниже это
---                  переживают (math.floor применяется в конце, не здесь)
function SB.Data.ToReferenceLevel(level)
    level = level or UnitLevel("player") or 1
    local maxLvl = SB.Data.GetMaxCharacterLevel()
    if maxLvl <= 0 then return level end
    return level * (SB.Data.REFERENCE_MAX_LEVEL / maxLvl)
end

--- true, если className нужно скрыть/заблокировать для ТЕКУЩЕГО
--- игрока на текущем сервере (т.е. это ограниченный класс на
--- Origins, и играем не за него).
function SB.Data.IsClassHiddenForPlayer(className)
    if not className or not SB.Data.HiddenClassesOnOrigins[className] then
        return false
    end
    if not SB.Data.IsOriginsRealm() then
        return false
    end
    -- Каноническое имя, а не UnitClass: у женского Друида оно вернуло бы
    -- «Друидка», сравнение с «Друид» провалилось бы, и класс скрылся бы
    -- от игрока, который им же и играет.
    return SB.Data.CanonicalClass("player") ~= className
end

--- Список классов, видимых текущему игроку (с учётом ограничения
--- Origins). Используется везде, где раньше перебирали SB.Data.Classes
--- напрямую для построения меню выбора класса.
function SB.Data.GetVisibleClasses()
    local result = {}
    for _, cn in ipairs(SB.Data.Classes) do
        if not SB.Data.IsClassHiddenForPlayer(cn) then
            table.insert(result, cn)
        end
    end
    return result
end

-- ============================================================
-- РАНГИ (МАСТЕРСТВО) И РЕАЛМ
--
-- Рангов в системе пять, но реалм видит только первые maxMastery из
-- них. Origins остаётся ровно таким, каким был — три ранга, пороги по
-- эталонной шкале, четвёртый круг заклинаний недоступен. Sanctuary с
-- капом 100 продолжает прогрессию Мастером и Героем.
--
-- Всё, что зависит от ранга (Config.Modifiers/MaxZeal/MaxPrepared/
-- MaxOrder/...), объявлено сразу на все пять — таблицы одинаковы для
-- обоих реалмов, и различие ровно одно: до какого ранга можно дойти.
-- ============================================================

--- Сколько рангов доступно на текущем реалме.
function SB.Data.GetMasteryCount()
    return math.min(SB.Data.GetRealm().maxMastery or SB.Data.BASE_MASTERY_COUNT,
                    #SB.Data.Masteries)
end

--- Список доступных рангов текущего реалма (по возрастанию).
function SB.Data.GetMasteryList()
    local out = {}
    for i = 1, SB.Data.GetMasteryCount() do
        out[i] = SB.Data.Masteries[i]
    end
    return out
end

--- Порядковый номер ранга (1 = Неофит) или nil для незнакомого имени.
function SB.Data.MasteryIndex(name)
    for i, m in ipairs(SB.Data.Masteries) do
        if m == name then return i end
    end
    return nil
end

--- Высший ранг, достижимый на текущем реалме.
function SB.Data.GetMaxMastery()
    return SB.Data.Masteries[SB.Data.GetMasteryCount()]
end

--- Приводит имя ранга к допустимому на этом реалме. Нужно на случай,
--- когда персонаж с сохранённым «Героем» открывается на Origins (общая
--- учётка, ручной realmOverride): без зажима он получил бы пятый круг
--- заклинаний там, где его нет.
function SB.Data.ClampMastery(name)
    local idx = SB.Data.MasteryIndex(name) or 1
    return SB.Data.Masteries[math.min(idx, SB.Data.GetMasteryCount())]
end

--- Ранг НЕКАСТЕРА по уровню персонажа.
--- Реалм может задать собственную таблицу порогов (Sanctuary: 10/35/60/
--- 75/90). Если её нет — работают исторические пороги 11/18 по эталонной
--- шкале, то есть Origins ведёт себя ровно как раньше.
function SB.Data.GetMasteryForLevel(level)
    level = level or UnitLevel("player") or 1

    local byLevel = SB.Data.GetRealm().masteryByLevel
    if byLevel then
        local result = SB.Data.Masteries[1]
        for _, pair in ipairs(byLevel) do
            if level >= pair[1] then result = pair[2] else break end
        end
        return SB.Data.ClampMastery(result)
    end

    local ref = SB.Data.ToReferenceLevel(level)
    if ref >= 18 then return SB.Data.ClampMastery("Эксперт") end
    if ref >= 11 then return SB.Data.ClampMastery("Адепт")   end
    return SB.Data.Masteries[1]
end

--- Максимум собственного ресурса некастера для КОНКРЕТНОГО ранга.
--- Отдельной функцией, потому что спрашивают её и про чужих игроков
--- (Core/Network.lua, Core/ResourceGrant.lua — там знают только имя
--- ранга из пакета, а не модель персонажа).
function SB.Data.MaxClassResourceFor(mastery)
    local cfg = SB.Data.Config
    return (cfg.ClassResourceByMastery or {})[mastery or ""]
        or cfg.MaxClassResource or 3
end

--- Максимальный круг заклинания, доступный рангу.
function SB.Data.MaxOrderFor(mastery)
    return (SB.Data.Config.MaxOrder or {})[mastery or ""] or 3
end

