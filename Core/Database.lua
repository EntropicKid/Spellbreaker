-- ============================================================
-- ПРОГРЕССИЯ ПО РЕАЛМАМ
--
-- Все формулы очков (атрибуты/навыки) и все таблицы порогов по
-- уровню (здоровье, бонус к броску, ранг некастеров — см.
-- Core/PlayerModel.lua) откалиброваны под максимальный уровень
-- REFERENCE_MAX_LEVEL = 25 (реалм Origins). На реалме с другим
-- максимальным уровнем (Sanctuary, кап 100) та же итоговая
-- прогрессия должна раскрываться к КОНЦУ прокачки, а не к 25-му
-- уровню — то есть растянуться пропорционально.
--
-- Механизм — один: текущий уровень персонажа переводится в
-- "уровень по эталонной шкале 1-25" через ToReferenceLevel, и это
-- значение подставляется в ОРИГИНАЛЬНЫЕ, НЕТРОНУТЫЕ формулы/таблицы.
-- Так на Origins (maxLevel = REFERENCE_MAX_LEVEL) число не меняется
-- вообще, а вся стретч-логика живёт в одном месте.
-- ============================================================

--- Максимальный уровень персонажа на текущем реалме.
function SB.Data.GetMaxCharacterLevel()
    return SB.Data.GetRealm().maxLevel or SB.Data.REFERENCE_MAX_LEVEL
end

--- Переводит реальный уровень персонажа в "уровень по эталонной шкале
--- 1-25", на которой откалиброваны формулы очков и таблицы порогов.
--- На Origins (maxLevel = 25) — тождественная функция.
--- @return number  может быть дробным — сравнения/формулы ниже это
---                  переживают (math.floor применяется в конце, не здесь)
function SB.Data.ToReferenceLevel(level)
    level = level or UnitLevel("player") or 1
    local maxLvl = SB.Data.GetMaxCharacterLevel()
    if maxLvl <= 0 then return level end
    return level * (SB.Data.REFERENCE_MAX_LEVEL / maxLvl)
end

--- true, если className нужно скрыть/заблокировать для ТЕКУЩЕГО
--- игрока на текущем сервере (т.е. это ограниченный класс на
--- Origins, и играем не за него).
function SB.Data.IsClassHiddenForPlayer(className)
    if not className or not SB.Data.HiddenClassesOnOrigins[className] then
        return false
    end
    if not SB.Data.IsOriginsRealm() then
        return false
    end
    -- Каноническое имя, а не UnitClass: у женского Друида оно вернуло бы
    -- «Друидка», сравнение с «Друид» провалилось бы, и класс скрылся бы
    -- от игрока, который им же и играет.
    if SB.Data.CanonicalClass("player") == className then return false end

    -- ПРЕДМЕТ ПРОБИВАЕТ СКРЫТОСТЬ, и это не поблажка, а весь смысл вещи.
    --
    -- Список скрытых классов писался тогда, когда классы раздавал только
    -- сервер: на Origins паладинов не создают, значит и школы их видеть
    -- незачем. С появлением предметов-ключей правило устарело и стало
    -- прямой поломкой: жрец с вещью «паладин-эксперт» в сумке не видел
    -- паладинской вкладки вовсе — вещь работала везде, кроме того
    -- единственного места, ради которого её и брали.
    local PM = SB.PlayerModel
    if PM and PM.HasClassItem and PM.HasClassItem(className) then
        return false
    end

    return true
end

-- ВИДНЫ ВСЕ КЛАССЫ, НА ОБОИХ РЕАЛМАХ.
---
--- Раньше отсюда выпадали классы, закрытые на Origins (паладин, монах,
--- рыцарь смерти, охотник на демонов): их там не создают, и книгу их
--- заклинаний было незачем показывать. Правило верное ровно до тех пор,
--- пока «показать» означало «дать взять».
---
--- Теперь не означает: закрытое рангом лежит в библиотеке серым и без
--- кнопки «Подготовить» (см. SB.Data.IsSpellLockedForPlayer), а отказ
--- живёт в PM.PrepareSpell и от видимости не зависит вовсе. Прятать
--- стало нечего — остался только вред: игрок не видел, чем эти классы
--- вообще занимаются, и не мог прочитать чужое заклинание, которое по
--- нему только что применили.
---
--- ДОСТУПНОСТЬ ЭТИМ НЕ ТРОНУТА. IsClassHiddenForPlayer как отвечал
--- «этот класс тебе не выдан», так и отвечает, и на нём по-прежнему
--- держатся и ранг школы (PM.GetClassRank), и отказ подготовить
--- ("class_hidden"). Изменилось одно: видимость больше не спрашивает
--- у него разрешения.
---
--- Функция оставлена (а не заменена на SB.Data.Classes в местах
--- вызова) ради одного: «какие школы показывать» и «какие вообще
--- бывают» — разные вопросы, и то, что сегодня они дают один ответ,
--- завтра может перестать быть правдой.
function SB.Data.GetVisibleClasses()
    local result = {}
    for _, cn in ipairs(SB.Data.Classes) do
        result[#result + 1] = cn
    end
    return result
end

-- ============================================================
-- РАНГИ (МАСТЕРСТВО) И РЕАЛМ
--
-- Рангов в системе пять, но реалм видит только первые maxMastery из
-- них. Origins остаётся ровно таким, каким был — три ранга, пороги по
-- эталонной шкале, четвёртый круг заклинаний недоступен. Sanctuary с
-- капом 100 продолжает прогрессию Мастером и Героем.
--
-- Всё, что зависит от ранга (Config.Modifiers/MaxZeal/MaxPrepared/
-- MaxOrder/...), объявлено сразу на все пять — таблицы одинаковы для
-- обоих реалмов, и различие ровно одно: до какого ранга можно дойти.
-- ============================================================

--- Сколько рангов доступно на текущем реалме.
function SB.Data.GetMasteryCount()
    return math.min(SB.Data.GetRealm().maxMastery or SB.Data.BASE_MASTERY_COUNT,
                    #SB.Data.Masteries)
end

--- Список доступных рангов текущего реалма (по возрастанию).
function SB.Data.GetMasteryList()
    local out = {}
    for i = 1, SB.Data.GetMasteryCount() do
        out[i] = SB.Data.Masteries[i]
    end
    return out
end

--- «2/5/8» — значения таблицы по рангам ТЕКУЩЕГО реалма, готовой
--- строкой для подсказок. Живёт здесь, а не рядом с подсказками,
--- потому что читают её две разные подсказки из двух файлов
--- (Core/Strings.lua и Core/Logic/Tooltips.lua), а Database грузится
--- раньше обоих.
---
--- Выписывать такие ряды руками нельзя: рангов три на Origins и пять на
--- Sanctuary, а сами числа лежат в Config и правятся при балансировке.
function SB.Data.RankValues(tbl)
    local parts = {}
    for _, m in ipairs(SB.Data.GetMasteryList()) do
        parts[#parts + 1] = tostring((tbl or {})[m] or 0)
    end
    return table.concat(parts, "/")
end

--- Настоящая ли это школа из SB.Data.Classes.
---
--- Поле class у заклинания списком не ограничено: у служебных стоит
--- «Эффект» или «Проверка», у кастомных заклинаний Ведущего — что угодно.
--- Спрашивают об этом там, где по имени школы делают вывод о персонаже
--- (см. SB.Logic.VerifyIncomingCast): о выдуманной школе никаких выводов
--- делать нельзя.
function SB.Data.IsRealClass(name)
    if not name or name == "" then return false end
    for _, c in ipairs(SB.Data.Classes) do
        if c == name then return true end
    end
    return false
end

--- Порядковый номер ранга (1 = Неофит) или nil для незнакомого имени.
function SB.Data.MasteryIndex(name)
    for i, m in ipairs(SB.Data.Masteries) do
        if m == name then return i end
    end
    return nil
end

--- Высший ранг, достижимый на текущем реалме.
function SB.Data.GetMaxMastery()
    return SB.Data.Masteries[SB.Data.GetMasteryCount()]
end

--- Приводит имя ранга к допустимому на этом реалме. Нужно на случай,
--- когда персонаж с сохранённым «Героем» открывается на Origins (общая
--- учётка, ручной realmOverride): без зажима он получил бы пятый круг
--- заклинаний там, где его нет.
function SB.Data.ClampMastery(name)
    local idx = SB.Data.MasteryIndex(name) or 1
    return SB.Data.Masteries[math.min(idx, SB.Data.GetMasteryCount())]
end

--- Ранг НЕКАСТЕРА по уровню персонажа.
--- Реалм может задать собственную таблицу порогов (Sanctuary: 10/35/60/
--- 75/90). Если её нет — работают исторические пороги 11/18 по эталонной
--- шкале, то есть Origins ведёт себя ровно как раньше.
-- ============================================================
-- ДВЕ ЛЕСТНИЦЫ УРОВНЕЙ У НЕКАСТЕРОВ
--
-- Некастерские школы открыты всем: их умения — выучка, а не магия, и
-- предметов ранга для них не бывает. Но владеть СВОЕЙ выучкой персонаж
-- обязан лучше, чем чужой, — иначе разбойник и воин одинаково хороши в
-- разбойничьем, и класс перестаёт что-либо значить.
--
-- Отсюда две лестницы:
--
--   СВОЯ ШКОЛА — раньше. На Origins: адепт с 10 уровня, эксперт с 18.
--   ЧУЖАЯ ШКОЛА — позже. На Origins: адепт с 15, эксперт с 21.
--
-- SANCTUARY ВЫВОДИТСЯ ИЗ ТЕХ ЖЕ ДОЛЕЙ. Пороги чужой школы заданы не
-- числами, а долей от потолка реалма: 60% на адепта, 84% на эксперта.
-- На Origins с его капом в 25 это ровно 15 и 21 — те числа, что и
-- задумывались; на Sanctuary со ста уровнями — 60 и 84. Выпиши мы числа
-- для каждого реалма отдельно, третий реалм пришлось бы добавлять сюда
-- руками, а забытая строка означала бы «чужая школа не растёт вовсе».
--
-- ЧУЖАЯ ШКОЛА НЕ ИДЁТ ВЫШЕ ЭКСПЕРТА. Мастер и Герой — это уже глубина,
-- до которой в чужой выучке не доходят; правил на них не задавали, и
-- выдумывать их со стороны хуже, чем остановиться на названном.
-- ============================================================
-- ДОЛИ ВЫНЕСЕНЫ В SB.Data, а не оставлены локальными: это ручка
-- баланса, её крутят, и прогон обязан следовать за ней сам. Пока числа
-- были заперты в файле, тесты помнили их наизусть — и падали от честной
-- правки, называя её поломкой.
SB.Data.ForeignRankAt = { adept = 0.60, expert = 0.90 }
local FOREIGN_ADEPT_AT  = SB.Data.ForeignRankAt.adept
local FOREIGN_EXPERT_AT = SB.Data.ForeignRankAt.expert

--- Ранг в СВОЕЙ школе по уровню персонажа.
function SB.Data.GetMasteryForLevel(level)
    level = level or UnitLevel("player") or 1

    local byLevel = SB.Data.GetRealm().masteryByLevel
    if byLevel then
        local result = SB.Data.Masteries[1]
        for _, pair in ipairs(byLevel) do
            if level >= pair[1] then result = pair[2] else break end
        end
        return SB.Data.ClampMastery(result)
    end

    -- Реалм без своей лестницы (Origins) — по эталонной шкале.
    local ref = SB.Data.ToReferenceLevel(level)
    if ref >= 18 then return SB.Data.ClampMastery("Эксперт") end
    if ref >= 10 then return SB.Data.ClampMastery("Адепт")   end
    return SB.Data.Masteries[1]
end

--- Ранг в ЧУЖОЙ некастерской школе по уровню персонажа.
--- Всегда не выше своей: доли подобраны так, что чужая лестница идёт
--- позади собственной на любом реалме.
function SB.Data.GetForeignMasteryForLevel(level)
    level = level or UnitLevel("player") or 1
    local cap = SB.Data.GetRealm().maxLevel or SB.Data.REFERENCE_MAX_LEVEL

    local rank = SB.Data.Masteries[1]
    if level >= math.floor(cap * FOREIGN_EXPERT_AT) then
        rank = "Эксперт"
    elseif level >= math.floor(cap * FOREIGN_ADEPT_AT) then
        rank = "Адепт"
    end
    return SB.Data.ClampMastery(rank)
end

--- Максимум собственного ресурса некастера для КОНКРЕТНОГО ранга.
--- Отдельной функцией, потому что спрашивают её и про чужих игроков
--- (Core/Network.lua, Core/ResourceGrant.lua — там знают только имя
--- ранга из пакета, а не модель персонажа).
function SB.Data.MaxClassResourceFor(mastery)
    local cfg = SB.Data.Config
    return (cfg.ClassResourceByMastery or {})[mastery or ""]
        or cfg.MaxClassResource or 3
end

--- Максимальный круг заклинания, доступный рангу.
function SB.Data.MaxOrderFor(mastery)
    return (SB.Data.Config.MaxOrder or {})[mastery or ""] or 3
end

--- Высший круг, СУЩЕСТВУЮЩИЙ на этом реалме, — тот, что открыт высшему
--- достижимому здесь рангу. На Origins это 3 (потолок — Эксперт), на
--- Sanctuary — 5.
function SB.Data.GetRealmMaxOrder()
    return SB.Data.MaxOrderFor(SB.Data.GetMaxMastery())
end

--- true, если круга с таким номером на реалме нет ВООБЩЕ.
---
--- Не путать с «не открыт рангом»: заклинание четвёртого круга на
--- Origins не станет доступным никогда и никому, потому что ранга,
--- который его открывает, на реалме не существует. Показывать такое в
--- библиотеке — обещать то, чего на сервере нет; поэтому оно не
--- «заблокировано», а не показано вовсе (см. SB.Library.UpdateList).
function SB.Data.IsOrderBeyondRealm(level)
    return (tonumber(level) or 0) > SB.Data.GetRealmMaxOrder()
end

-- ============================================================
-- ЧТО ВООБЩЕ ПОКАЗЫВАТЬ В БИБЛИОТЕКЕ
--
-- Прежнее правило смотрело на РЕАЛМ: на Origins прятались круги выше
-- третьего, потому что ранга, который их открывает, здесь нет. Правило
-- верное, но грубое — оно одинаково для всех и ничего не знает про
-- самого игрока. Воин-адепт видел у себя третий круг, изучить который
-- не может, и разница между «есть в игре» и «доступно мне» стиралась.
--
-- Теперь смотрим на РАНГ В ЭТОЙ ШКОЛЕ. Библиотека показывает ровно те
-- круги, которые персонажу открыты сейчас:
--   воин-адепт        — заговоры, 1 и 2; третий и выше скрыты;
--   маг-неофит        — заговоры и 1; второй и выше скрыты;
--   разбойник-эксперт — на Origins всё, что у разбойника есть.
--
-- ДВА РАЗНЫХ «НЕДОСТУПНО», И ПОКАЗЫВАТЬ ИХ НАДО ПО-РАЗНОМУ.
--
-- Раньше оба сводились к одному ответу «прятать», и книга у неофита
-- была куцей: он не видел, что его ждёт впереди, и не мог даже
-- прочитать карточку заклинания, до которого ему расти один ранг.
--
--   НИКОГДА — предмет (у него своя вкладка) и круг, которого на реалме
--   нет вовсе. Ни то, ни другое в книге заклинаний не появится ни при
--   каком развитии персонажа, и место в списке занимать им незачем.
--
--   ПОКА — круг существует, но рангом ещё не открыт. Это ровно то, за
--   чем в книгу и лезут: посмотреть, что будет доступно. Такие
--   остаются в списке серыми — читать можно, готовить нельзя
--   (см. SB.Data.IsSpellLockedForPlayer).
--
-- @param spell table  заклинание (нужны поля level и class)
-- @return boolean  прятать ли его от этого персонажа СОВСЕМ
function SB.Data.IsSpellHiddenFromLibrary(spell)
    if not spell then return false end
    -- Предмет в списке заклинаний не показываем вовсе: у него своя
    -- вкладка и свои ячейки (см. Core/Items.lua). Круг у него нулевой,
    -- так что иначе он лёг бы к заговорам родной школы.
    if SB.Items and SB.Items.IsItem and SB.Items.IsItem(spell) then return true end
    -- Круга нет на реалме вовсе — прячем независимо от рангов.
    return SB.Data.IsOrderBeyondRealm(tonumber(spell.level) or 0)
end

-- Закрыто РАНГОМ — то есть откроется, если персонаж вырастет.
--
-- Серое в библиотеке, карточка открывается, «Подготовить» нет.
-- Отказ подготовить такое живёт не здесь, а в PM.PrepareSpell
-- ("order_too_high"): сюда заклинание приходит и мимо библиотеки —
-- перетаскиванием карточки, кастомом с чужого реалма по сети.
-- @return boolean locked, number|nil maxOrder  до какого круга открыт
function SB.Data.IsSpellLockedForPlayer(spell)
    if not spell then return false end
    if SB.Data.IsSpellHiddenFromLibrary(spell) then return false end

    local PM = SB.PlayerModel
    if not PM or not PM.GetMaxPrepareOrder then return false end

    -- GetMaxPrepareOrder отвечает и про закрытую школу (-1), и про
    -- служебные классы без школы (потолок по рангу героя). Отдельной
    -- развилки здесь не надо — она была бы копией той, что уже там.
    local maxOrder = PM.GetMaxPrepareOrder(spell.class)
    return (tonumber(spell.level) or 0) > maxOrder, maxOrder
end

-- Прежнее имя — «недоступно вообще, как ни посмотри». Оставлено
-- потому, что вопрос «могу ли я это взять» задают и вне библиотеки, и
-- ответ на него по-прежнему один: сумма обеих причин.
function SB.Data.IsSpellBeyondPlayer(spell)
    return SB.Data.IsSpellHiddenFromLibrary(spell)
        or SB.Data.IsSpellLockedForPlayer(spell)
end

-- ============================================================
-- ЧТО СБИВАЕТ КОНЦЕНТРАЦИЮ
--
-- РАНЬШЕ СБИВАЛ УРОН, по умолчанию и всем подряд. Правило звучало
-- складно — «поддерживаемое заклинание требует внимания, а удар внимание
-- отнимает», — но за столом означало другое: концентрацию не держал
-- никто. В свалке урон прилетает каждый круг, и любой поддерживаемый
-- эффект жил ровно до первой стрелы, прилетевшей мимоходом.
--
-- ТЕПЕРЬ СБИВАЕТ ТО, ЧТО ОТНИМАЕТ ВОЛЮ, а не здоровье: оглушение,
-- жёсткий контроль, страх. Разница осмысленная — чтобы сорвать чужое
-- сосредоточение, нужно потратить на это отдельную способность, а не
-- просто оказаться в бою.
--
-- ЗАМЕДЛЕНИЯ ЗДЕСЬ НЕТ НАМЕРЕННО. Оно отнимает метры, а не голову;
-- думать оно не мешает.
--
-- Семейство, а не список эффектов: метка уже стоит на самих эффектах и
-- используется для взаимоисключения (см. врезку о family в README).
-- Новый контроль получит и сбив, ничего здесь не трогая.
-- ============================================================
SB.Data.ConcentrationBreakers = {
    ["Оглушение"] = true,
    ["Контроль"]  = true,
    ["Страх"]     = true,
}

-- ============================================================
-- ЧТО РЕЖЕТ «ВОЛЯ»
--
-- Навык срезал срок ЛЮБОМУ входящему дебаффу — и это была не стойкость,
-- а универсальная скидка: развитая Воля одинаково укорачивала и
-- оглушение, и кровотечение, и яд, и проклятие, и поджог. То есть один
-- навык защищал от всей вредной половины библиотеки сразу, а школы, у
-- которых для этого есть свои ответы (резисты, рассеивание, лечение),
-- обесценивались об него.
--
-- Теперь Воля — про ВМЕШАТЕЛЬСТВО В ВОЛЮ, и только: оглушение, контроль,
-- ослепление, замедление. Ровно то, чему сопротивляются, стиснув зубы, —
-- а не то, что течёт из раны.
--
-- ── ПОЧЕМУ ДВА СПИСКА, А НЕ ОДИН ────────────────────────────
--
-- Три из четырёх выражаются СЕМЕЙСТВОМ (family): оглушение, контроль и
-- замедление объявлены им у трёх десятков эффектов, и семейство читается
-- одинаково на любом пути доставки (см. врезку о family ниже).
--
-- А ослепление семейством не выражается, и заводить его нельзя: family
-- означает ВЫТЕСНЕНИЕ, и «Дымовая завеса» разбойника начала бы снимать
-- «Рой насекомых» друида — они стали бы одним семейством, хотя общего у
-- них ровно ничего. Зато все слепящие эффекты лежат в одном ГНЕЗДЕ —
-- eff_blinded и отщеплённые от него, — и это тот же принцип, по
-- которому в библиотеке устроены щиты и обереги.
--
-- Поэтому список гнёзд отдельный и матчится ПРЕФИКСОМ: новое ослепление
-- в библиотеке заводят отщеплением от eff_blinded, и оно подхватится
-- само, без правки этого файла. Прогон следит, чтобы гнездо не
-- разъехалось со списком.
-- ============================================================
SB.Data.WillCutFamilies = {
    ["Оглушение"]  = true,
    ["Контроль"]   = true,
    ["Замедление"] = true,
}

SB.Data.WillCutNests = { "eff_blinded" }

--- Режет ли «Воля» срок этого эффекта.
---
--- СТРАХА ЗДЕСЬ НЕТ намеренно, хотя он и сбивает концентрацию
--- (см. ConcentrationBreakers): страх — это чары над чувствами, у них
--- своя защита, и складывать два разных списка в один значило бы решить
--- за баланс, что «бежать в ужасе» и «стоять оглушённым» — одно и то же.
--- @param effectID string|nil  id эффекта-контейнера
--- @return boolean
function SB.Data.WillCutsDuration(effectID)
    if type(effectID) ~= "string" then return false end

    local family = SB.Data.GetFamily and SB.Data.GetFamily(effectID)
    if family and SB.Data.WillCutFamilies[family] then return true end

    for _, nest in ipairs(SB.Data.WillCutNests) do
        -- Само гнездо И всё отщеплённое от него: «eff_blinded» и
        -- «eff_blinded_smoke_bomb» — одно и то же ослепление.
        if effectID == nest or effectID:sub(1, #nest + 1) == (nest .. "_") then
            return true
        end
    end
    return false
end

