-- Поток — заклинание, которое не заканчивается вместе с кастом. После
-- применения оно оставляет НА САМОМ ЗАКЛИНАТЕЛЕ активный эффект-
-- «держатель»; пока держатель висит, ЛКМ по его иконке повторяет
-- заклинание БЕСПЛАТНО и всегда нулевым кругом — вливать ресурс в
-- продолжение нельзя, сила потока задана первым кастом.
--
-- Объявляется ОДНИМ полем на самом заклинании:
--
--   channel = 3,      -- ровно три бесплатных продолжения
--   channel = true,   -- столько продолжений, сколько ходов в duration
--
-- Держатель создаётся ЗДЕСЬ, автоматически, с id "eff_channel_<id>".
-- Заводить его руками в Spells/Effects.lua не нужно: у него нет ни mods,
-- ни tick, он ничего не меняет в параметрах и существует ровно как
-- кнопка «продолжить». Поэтому же он не показывается в библиотеке —
-- её фильтр отсекает isContainer и класс «Эффект» (см. UI/Library.lua).
--
-- Почему держатель, а не «каст длится N ходов»: ход в системе — это
-- единица, которую игрок тратит осознанно, и растянутое заклинание
-- должно эти ходы РАСХОДОВАТЬ, а не идти фоном. Нажатие по иконке и
-- есть потраченный ход: оно тикает все прочие эффекты (SpendTurn) и
-- требует нового броска, просто не требует ресурса.
-- ============================================================

--- Сколько бесплатных продолжений даёт поток этого заклинания.
---
--- БЕССРОЧНОЕ ЗАКЛИНАНИЕ ДЕРЖИТ БЕССРОЧНЫЙ ПОТОК. duration = -1 значит
--- «до Долгого Отдыха» — и держатель обязан жить столько же, иначе
--- получается заклинание, которое висит вечно, а повторить его можно
--- ровно раз. Ограничителем у такого потока служит не счётчик, а сама
--- цена повтора: ход, а у «Жизнеотвода» ещё и здоровье.
---
--- То же самое числом: channel = -1 читается как «без счёта».
--- @return number  -1 (SB.ActiveEffects.INFINITE) — без ограничения
function SB.Data.GetChannelUses(spell)
    if not spell or not spell.channel then return 0 end

    local INFINITE = (SB.ActiveEffects and SB.ActiveEffects.INFINITE) or -1
    if tonumber(spell.duration) == -1 then return INFINITE end

    if spell.channel == true then
        return math.max(1, math.floor(tonumber(spell.duration) or 1))
    end
    local n = math.floor(tonumber(spell.channel) or 1)
    if n < 0 then return INFINITE end
    return math.max(1, n)
end

local function RegisterChannelHolder(spell)
    local holderID = "eff_channel_" .. spell.id
    spell.channelEffect = holderID

    SB.Data.Spells[holderID] = {
        id          = holderID,
        name        = "Поток: " .. (spell.name or spell.id),
        icon        = spell.icon,
        description = "Заклинание держится потоком. |cFFFFFFFFЛКМ|r — повторить его "
                   .. "бесплатно, не вливая ресурс: повтор тратит ход и одно "
                   .. "применение, но требует нового броска. Оборвать поток — ПКМ.",
        class       = "Эффект",
        key         = "Effect",
        level       = 0,
        resistable  = false,
        isCantrip   = false,
        isContainer = true,
        -- Ради этого поля всё и затевалось: пассивный эффект на ЛКМ не
        -- реагирует вовсе (см. Core/ActiveEffects.lua), а держатель — это
        -- кнопка, и клик по нему обязан что-то делать.
        isPassive   = false,
        -- Что именно повторяет ЛКМ. Обработчик ACTIVE_EFFECT_CAST по
        -- умолчанию кастует сам контейнер; здесь он перенаправляется на
        -- исходное заклинание.
        castSpell   = spell.id,
    }
end

