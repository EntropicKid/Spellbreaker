function SB.UI.MakeSpellLink(spell)
    return "|cFF9933FF|Hspellbreaker:" .. spell.id .. "|h[" .. spell.name .. "]|h|r"
end

--- Показать заклинание группе (Shift+ЛКМ по карточке или строке
--- библиотеки). Уходит по КАНАЛУ АДДОНА, а не через SendChatMessage:
--- клиент вырезает из обычного чата все незнакомые ему |H-ссылки, и
--- собеседник получил бы голый текст без карточки. Через свой канал
--- ссылка доезжает живой и открывает у получателя ShowDetail — ровно
--- как ссылки в боевых сообщениях.
--- Вне группы рассылать некому, но локально строку показываем: так
--- видно, что нажатие вообще сработало.
function SB.UI.ShareSpellLink(spell)
    if not spell or not spell.id then return end
    -- Показ заклинания — такая же рассылка в общий канал, как бросок, и
    -- жмётся он мышью ещё легче. Общий с бросками счётчик темпа
    -- (см. Core/Cooldowns.lua).
    if SB.Cooldowns and not SB.Cooldowns.Check(SB.Cooldowns.ROLL) then return end
    if SB.Cooldowns then SB.Cooldowns.Start(SB.Cooldowns.ROLL) end

    local G   = SB.Theme.MSG_BODY
    local msg = SB.Theme.MSG_TAG .. "[Spellbreaker]:|r " ..
        G .. UnitName("player") .. " показывает заклинание |r" .. SB.UI.MakeSpellLink(spell)
    if IsInGroup() then
        SB.Events.Fire("BROADCAST_LOG", msg, SB.LogRank.ACTION)
    else
        SB.Events.Fire("LOG_MESSAGE_RECEIVED", msg)
    end
end

--- Модификатор броска в тексте сообщения.
---
--- ПРОСТОЕ ЧИСЛО, А НЕ ССЫЛКА — как и у броска (см. RollText ниже).
--- Раньше здесь была |Hsbmod|h с ЗАШИТОЙ ВНУТРЬ разбивкой по источникам,
--- и стоила она дороже всего остального в аддоне вместе взятого:
---
---   • в тексте сообщения ссылка занимала «мастерство=8~уровень=30~
---     Наука=12~класс=4~…» — 60-120 символов вместо трёх, И ЭТО В КАЖДОЙ
---     строке боя, а в ПвП-размене таких модификаторов два;
---   • ту же разбивку пакет вёз ВТОРОЙ РАЗ отдельным полем modParts —
---     таблицей из 4-8 записей, которую приходилось паковать (SlimParts)
---     и распаковывать на другой стороне.
---
--- Своя разбивка никуда не делась: она живёт на бейджах атаки и защиты
--- в шапке главного окна и считается локально, ничего не требуя от сети.
--- Пропала только чужая — то есть возможность узнать, из чего именно
--- сложился модификатор соседа. Проверку честности это не ослабило:
--- она никогда не держалась на подсказке, которую рисует тот же клиент,
--- что и присылает числа, — см. SB.Logic.VerifyIncomingCast.
--- @param total number
--- @param labelText string|nil  что показать вместо «±total» (сжатый
---        отчёт о площадном залпе показывает там итог броска)
function SB.UI.ModText(total, labelText)
    total = tonumber(total) or 0
    local sign = (total >= 0) and "+" or ""
    return "|cFF66CCFF[" .. (labelText or (sign .. total)) .. "]|r"
end

--- Результат броска кубика в тексте сообщения.
---
--- ПРОСТОЕ ЧИСЛО, А НЕ ССЫЛКА. Раньше здесь была наводимая |Hsbroll|h,
--- показывавшая «использованные грани rollMin-rollMax». Границы
--- перестали быть настройкой (кубик всегда d100, см.
--- SB.Logic.GetRollRange), и подсказка свелась к строке «1-100» —
--- то есть к тому, что и так известно всем за столом.
---
--- Убрано это не только ради чистоты. Ссылка ехала В КАЖДОЙ строке
--- боевого лога по сети: «|Hsbroll:57~1~100|h[57]|h» это 26 символов
--- против четырёх у голого «[57]», а в сообщении о ПвП-размене таких
--- бросков два. Плюс на один тип ссылки меньше проверять санитайзеру
--- входящего лога (см. SanitizeIncomingLog в Core/Network.lua).
---
--- Оставлено функцией, а не заинлайнено: цвет броска должен меняться в
--- одном месте, а звали его из десяти.
--- @param roll number
function SB.UI.RollText(roll)
    return "|cFFFF9900[" .. tostring(roll) .. "]|r"
end

-- ============================================================
-- ЧИСЛО ИЗМЕНЕНИЯ ЗДОРОВЬЯ (урон / исцеление).
--
-- РАНЬШЕ ЗДЕСЬ БЫЛА ССЫЛКА С ПОДСКАЗКОЙ. В неё зашивалась вся арифметика
-- удара — база, крит, скейлинг, броня, — чтобы любой мог навести мышь и
-- убедиться, что цифра не выдумана. Идея верная, цена — нет: строка
-- «|Hsbamt:dmg~4~6~10~base=3~Сила=2~crit=2~броня=-3|h[4]|h» это 76 байт
-- против 15 у голого числа, и едет она в КАЖДОМ боевом сообщении, то
-- есть занимает около четверти строки. Канал аддонов узкий, и платить
-- четвертью каждого удара за подсказку, в которую заглядывают раз в
-- сцену, дорого.
--
-- ЧЕСТНОСТЬ ОТ ЭТОГО НЕ ПОСТРАДАЛА, потому что держалась она не на
-- подсказке. Числа соседа проверяет SB.Logic.VerifyIncomingCast: он
-- пересчитывает чужой бросок по статусу, который тот и так рассылает, и
-- ловит и кубик вне диапазона, и итог, не равный сумме, и вложенный
-- ресурс сверх круга. Проверка автоматическая, идёт у каждого получателя
-- и не стоит ни байта — в отличие от подсказки, в которую надо было
-- догадаться навести мышь.
-- ============================================================

--- @param kind   string  "dmg" (урон), "heal" (исцеление) или "eff"
---        (произвольный сдвиг — знак берётся у самого amount)
--- @param amount number  итоговая величина; для dmg/heal положительная
function SB.UI.AmountText(kind, amount)
    local positive = (kind == "heal") or (kind == "eff" and amount >= 0)
    local color = positive and "|cFF44DD66" or "|cFFFF5555"
    -- Знак рисуем только у "eff": там число само по себе, без окружающего
    -- текста. У урона и лечения направление уже сказано словом рядом
    -- («Урон:», «теряет», «восполняет»), и «Урон: [-3]» читалось бы как
    -- масло масляное.
    local sign = (kind == "eff" and amount >= 0) and "+" or ""
    return color .. "[" .. sign .. amount .. "]|r"
end

-- ============================================================
-- Общий "стартовый" тултип заклинания (имя + описание) — используют
-- ActiveEffects.lua/CustomSpells.lua вместо того, чтобы каждый раз
-- повторять SetOwner+StyleTooltip+SetText+описание.
-- НЕ вызывает Show() сам — вызывающий код может дописать свои строки
-- (осталось применений, статус эффекта, ЛКМ/ПКМ-подсказки и т.п.),
-- а завершить обязан сам вызовом GameTooltip:Show().
-- Возвращает false, если spell отсутствует (тултип не открыт).
--
-- ОПЦИИ ТАБЛИЦЕЙ, А НЕ ЧЕРЕДОЙ ФЛАГОВ. Их две, и обе про то, какие
-- строки печатать; позиционными булевыми хвостами «(owner, sp, anchor,
-- true, nil, true)» на месте вызова не прочитать ни одной.
--   • opts.showKey — дописать spell.key (ключ дескриптора);
--   • opts.noDesc  — НЕ печатать ролевое описание.
--
-- ЗАЧЕМ ПРЯТАТЬ ОПИСАНИЕ. Оно у заклинаний длинное и намеренно
-- художественное — абзац на пять-шесть строк, — и на своём месте, в
-- карточке библиотеки, читается. А в подсказке кнопки на панели оно
-- выдавливает всё остальное: панель открывают в бою, и нужны там числа
-- («Атака −40, Урон 1»), а не рассказ о том, как пистоли неудобны.
-- ============================================================
function SB.UI.StartSpellTooltip(owner, spell, anchor, opts)
    if not spell then return false end
    opts = opts or {}
    GameTooltip:SetOwner(owner, anchor or "ANCHOR_RIGHT")
    SB.Theme.StyleTooltip(GameTooltip)
    GameTooltip:SetText(spell.name or "?", 1, 0.82, 0, true)
    if not opts.noDesc and spell.description and spell.description ~= "" then
        GameTooltip:AddLine(spell.description, 0.85, 0.85, 0.85, true)
    end
    if opts.showKey and spell.key then
        GameTooltip:AddLine(spell.key, 0.8, 0.8, 0.8)
    end
    return true
end

-- ============================================================
-- ЗАПИСЬ БРОСКА — ОДНОЙ ФОРМУЛОЙ
--
-- «Бросок: [14] + [5] (Итог: 19)» говорит одно и то же трижды: словом
-- «Бросок», знаком «+» и словом «Итог». Тридцать знаков там, где хватает
-- четырнадцати, — и это в КАЖДОЙ строке боя, а в ПвП-размене таких
-- записей две.
--
-- «[14]+[5]=19» короче вдвое и читается ровно так же: цветные числа
-- по краям, серое равенство посередине. Слово «Бросок» пишет тот, кто
-- зовёт, — и только если из окружающего текста непонятно, чей бросок.
-- ============================================================
--- @param roll  number  кубик
--- @param mod   number  модификатор
--- @param total number|nil  итог; без него складывается сам
--- ЗНАК «+» МЕЖДУ ЧИСЛАМИ НЕ СТАВИМ: ModText уже печатает знак внутри
--- скобок, и вместе выходило «[14]+[+5]» — плюс дважды подряд. Скобки
--- разного цвета (бросок оранжевый, модификатор голубой) разделяют
--- слагаемые сами, а у отрицательного модификатора «[14][-3]=11»
--- остаётся единственно верным прочтением.
function SB.UI.RollLine(roll, mod, total, grey)
    grey = grey or SB.Theme.MSG_BODY
    return SB.UI.RollText(roll) .. SB.UI.ModText(mod) ..
           grey .. "=" .. (total or ((tonumber(roll) or 0) + (tonumber(mod) or 0)))
end

-- ============================================================
-- ТЕГ [Spellbreaker] — ОДИН РАЗ НА ДЕЙСТВИЕ
--
-- Одно действие в бою рождает не одну строку, а пять-восемь: заголовок
-- каста, урон, ответ щита, тик яда, «ход перешёл». Каждая начиналась
-- с «[Spellbreaker]:» — пятнадцать знаков, повторённых восемь раз, и
-- это ещё у ОДНОГО участника. В драке впятером тег занимал больше
-- места, чем всё, ради чего строки написаны.
--
-- Тег нужен, чтобы отличить речь аддона от чужого чата, — и для этого
-- достаточно одного раза на блок. Остальные строки блока получают
-- точку того же цвета: она говорит «это продолжение», не повторяя
-- слова целиком.
--
-- БЛОК — ЭТО КАДР. Всё, что порождено одним действием, печатается в
-- одном кадре (см. FlushLogQueue в Core/Network.lua — он для того и
-- заведён, чтобы собрать строки кадра и разложить их по рангу).
-- Строки, приехавшие по сети от соседей, приходят своими кадрами и
-- тег сохраняют — то есть блок соседа отделён от нашего, как и должен.
--
-- Режется ТОЛЬКО ДЛЯ ЧАТА. В окно логов строка уходит целиком: там
-- ищут глазами по тегу и читают историю вразбивку, а не блоками.
-- ============================================================

--- Метка продолжения блока. Точка, а не отступ: чат съедает ведущие
--- пробелы в некоторых шрифтах, а точку видно всегда.
SB.UI.CHAT_CONT = "|cFF9933FF\194\183|r "

local lastTagFrame = nil

--- Убрать тег, если строка — продолжение того же блока.
--- @param msg string   готовая строка со всеми цветами
--- @param now number|nil  время кадра; без него берётся GetTime()
--- @return string
function SB.UI.CollapseTag(msg, now)
    if type(msg) ~= "string" then return msg end
    -- БЕЗ ЧАСОВ НЕ СХЛОПЫВАЕМ ВОВСЕ. Если бы часов не оказалось и мы
    -- подставили ноль, «время кадра» стало бы одинаковым НАВСЕГДА — и
    -- тег исчез бы из всех строк, кроме самой первой за сессию. Лишний
    -- тег — мелкая некрасивость, пропавший — потерянная возможность
    -- отличить речь аддона от чужого чата.
    now = now or (GetTime and GetTime())
    if not now then return msg end

    local first = (lastTagFrame ~= now)
    lastTagFrame = now
    if first then return msg end

    -- Тег написан в аддоне четырьмя способами сразу: «[Spellbreaker]:|r»,
    -- «[Spellbreaker]|r:», «[Spellbreaker]:» внутри цвета и просто
    -- «[Spellbreaker] » без двоеточия. Одним шаблоном это не разобрать:
    -- в шаблонах Lua нет необязательных ГРУПП — «?» действует только на
    -- один знак. Поэтому ищем сам тег, а хвост срезаем по кусочку.
    local i, j = msg:find("[Spellbreaker]", 1, true)
    -- Только в начале строки: код цвета — ровно десять знаков, значит
    -- тег начинается на первом или на одиннадцатом. Дальше — уже не тег,
    -- а имя аддона внутри текста, и трогать его нельзя.
    if not i or i > 11 then return msg end

    local head = msg:sub(1, i - 1)
    local rest = msg:sub(j + 1)
    repeat
        local was = rest
        rest = rest:gsub("^|r", "")
        rest = rest:gsub("^%s+", "")
        rest = rest:gsub("^:", "")
    until rest == was

    return SB.UI.CHAT_CONT .. head .. rest
end

-- ============================================================
-- ИМЕНА В СТРОКАХ БОЯ — ЦВЕТОМ КЛАССА
--
-- ЗАЧЕМ. Строка размена — это два имени, два броска и итог, и все пять
-- набраны одним цветом. Взгляд ищет в ней «кто по кому», а находит
-- сплошное золото. Цвет класса отвечает на это без единого лишнего
-- слова: воин красный, жрец белый, маг голубой — и строка читается с
-- первого взгляда, ещё до того, как прочитаны слова.
--
-- НИ БАЙТА ПО СЕТИ, и это главное требование к этой затее.
--
-- Класс сокомандника клиент знает сам — UnitClass по юнит-токену
-- (см. Build ниже): состав группы игрок и так видит, и спрашивать о нём
-- группу было бы странно. Для тех, кого в группе уже нет, класс берётся
-- из фонового статуса, который и без нас приезжает в каждом STATUS
-- (см. PM.GetStatusSnapshot — поле class там лежало с самого начала).
-- То есть новых полей в пакетах нет, новых пакетов нет, и на канал эта
-- правка не влияет вовсе.
--
-- КРАСИТСЯ ГОТОВАЯ СТРОКА, а не каждое место, где имя подставляется.
-- Мест этих в аддоне под сотню — заголовки залпов, ответы задетых,
-- тики, объявления очереди, речь существа, — и покрасить имя в каждом
-- значило бы завести сотню точек, из которых половина забылась бы, а
-- вторая половина разъехалась бы по оттенкам. Проход по итоговой строке
-- ровно один и стоит он один раз на строку (см. врезку про порядок в
-- SB.UI.CollapseTag — тот устроен так же и по той же причине).
--
-- ── ЧЕМ ЭТО СЛОЖНЕЕ, ЧЕМ КАЖЕТСЯ ────────────────────────────
--
-- ЦВЕТА В WoW НЕ ВКЛАДЫВАЮТСЯ, и с этим приходится считаться дважды.
--
-- Во-первых, «|r» закрывает не «последний открытый», а вообще всё:
-- вставь мы «|cffC41F3BЛайка|r» внутрь золотой строки — и ВЕСЬ остаток
-- строки потерял бы золото. Поэтому проход идёт слева направо и помнит,
-- какой цвет открыт прямо сейчас: после своего «|r» он открывает его
-- заново.
--
-- Во-вторых, чужой цвет СНАЧАЛА ЗАКРЫВАЕТСЯ, и только потом открывается
-- свой: «…|r|cffC41F3BЛайка|r|cFFCFAFDA…». Написать «|c» прямо внутри
-- уже открытого «|c» — значит положиться на то, как клиент разбирает
-- вложение, которого в его разметке нет; так делать нельзя даже когда
-- это случайно работает.
--
-- ГРАНИЦЫ СЛОВА СЧИТАЮТСЯ ПО БАЙТАМ. Шаблоны Lua побайтовые, и «%a»
-- кириллицу не ловит вовсе — «%a» на «Лайка» не сработает ни разу.
-- Поэтому границей считается «байт не буква и не цифра И не старше
-- ASCII»: любой байт от 128 и выше — это середина кириллического слова,
-- и имя, найденное там, именем не является. Без этого «Лай» красился бы
-- внутри «Лайка», а «Ал» — внутри «Алхимия».
--
-- И ГРАНИЦА СЧИТАЕТСЯ ПО ТЕКСТУ, А НЕ ПО СЫРОЙ СТРОКЕ. Это стоило
-- первой версии почти всей её работы: имя в строках аддона почти всегда
-- стоит СРАЗУ за цветом («|cFFCFAFDAЛайка применяет»), а последний знак
-- кода цвета — шестнадцатеричная цифра, то есть с точки зрения байтов
-- «буква A». Проверка честно считала это серединой слова и имя
-- пропускала. Со стороны выглядело ровно так: «работает только на белых
-- сообщениях» — то есть на тех, где перед именем нет кода цвета.
-- Поэтому помним последний ТЕКСТОВЫЙ байт, а управляющие
-- последовательности границу обнуляют.
--
-- ССЫЛКИ ПЕРЕПРЫГИВАЕМ ЦЕЛИКОМ. Внутри «|H…|h[текст]|h» свой «|r» рвёт
-- саму ссылку, а не только цвет: щёлкнуть по ней стало бы нельзя. Имя
-- игрока внутри названия заклинания — случай редкий, но чинить его
-- потом дороже, чем обойти сейчас. Так же и с иконками «|T…|t».
--
-- ДЛИННОЕ ИМЯ ВПЕРЁД. Два имени в группе могут начинаться одинаково
-- («Лай» и «Лайка»), и проверять их в случайном порядке значит иногда
-- красить половину второго. Внутри каждой корзины имена лежат по
-- убыванию длины.
-- ============================================================

local nameColor  = {}       -- [имя] = "ffRRGGBB"
local nameByByte = {}       -- [первый байт] = { имя, … } по убыванию длины
local nameCacheOk = false

--- Цвет класса строкой для «|c», или nil — токена не знаем.
local function HexOfToken(token)
    local c = token and RAID_CLASS_COLORS and RAID_CLASS_COLORS[token]
    if not c then return nil end
    -- Из r/g/b, а не из c.colorStr: поле есть не на всех сборках, а
    -- три числа есть везде.
    return string.format("ff%02x%02x%02x",
        math.floor((tonumber(c.r) or 1) * 255 + 0.5),
        math.floor((tonumber(c.g) or 1) * 255 + 0.5),
        math.floor((tonumber(c.b) or 1) * 255 + 0.5))
end

--- Забыть, кто какого класса. Состав группы и статусы меняются, а
--- перебирать сорок юнитов на каждую строку боя незачем.
function SB.UI.InvalidateNameColors()
    nameCacheOk = false
end

local function Build()
    nameColor, nameByByte, nameCacheOk = {}, {}, true

    local function Put(name, hex)
        if not name or not hex then return end
        name = (Ambiguate and Ambiguate(name, "none")) or name
        if name == "" or nameColor[name] then return end
        nameColor[name] = hex
    end

    -- ── 1. ГРУППА: класс спрашиваем у своего клиента ────────
    if UnitClass then
        local function Take(unit)
            if UnitExists and not UnitExists(unit) then return end
            if UnitIsPlayer and not UnitIsPlayer(unit) then return end
            local _, token = UnitClass(unit)
            Put(UnitName and UnitName(unit), HexOfToken(token))
        end
        -- «player» в party1..4 не входит (только в raid1..N) — отдельно.
        Take("player")
        if IsInGroup and IsInGroup() then
            local raid   = IsInRaid and IsInRaid()
            local prefix = raid and "raid" or "party"
            local count  = raid and (MAX_RAID_MEMBERS or 40)
                                or (MAX_PARTY_MEMBERS or 4)
            for i = 1, count do Take(prefix .. i) end
        end
    end

    -- ── 2. СТАТУСЫ: кто прислал о себе класс ───────────────
    -- Вторым заходом, а не первым: у своего клиента класс точный, а в
    -- статусе — то, что игрок о себе сообщил. Совпадают они всегда, но
    -- правило «точное важнее присланного» здесь то же, что в сверке
    -- чужого каста.
    for name, st in pairs(SB.Data.PlayersStatus or {}) do
        if type(st) == "table" and type(st.class) == "string" then
            Put(name, HexOfToken(SB.Data.ClassColorTokens[st.class]))
        end
    end

    for name in pairs(nameColor) do
        local b = name:byte(1)
        if b then
            nameByByte[b] = nameByByte[b] or {}
            table.insert(nameByByte[b], name)
        end
    end
    for _, bucket in pairs(nameByByte) do
        table.sort(bucket, function(a, b) return #a > #b end)
    end
end

--- Байт, который не может стоять на границе имени: буква, цифра или
--- любой байт UTF-8 выше ASCII (то есть середина слова).
local function IsWordByte(b)
    if not b then return false end
    return (b >= 48 and b <= 57)
        or (b >= 65 and b <= 90)
        or (b >= 97 and b <= 122)
        or b >= 128
end

--- Покрасить имена известных игроков в готовой строке.
---
--- Чистая функция от строки — ради прогона: сеть, кадры и фреймы сюда не
--- заходят, и проверить её можно без игры.
--- @param msg string  готовая строка со всеми своими цветами
--- @return string
function SB.UI.ColorNames(msg)
    if type(msg) ~= "string" or msg == "" then return msg end
    if not nameCacheOk then Build() end
    if next(nameColor) == nil then return msg end

    local out, i, n = {}, 1, #msg
    local active    = nil      -- какой цвет открыт прямо сейчас
    -- Последний ТЕКСТОВЫЙ байт: управляющая последовательность границу
    -- слова обнуляет (см. врезку). Ноль на старте — начало строки тоже
    -- граница.
    local prev      = nil

    while i <= n do
        local two = msg:sub(i, i + 1)

        if two == "|c" then
            out[#out + 1] = msg:sub(i, i + 9)
            active, prev  = msg:sub(i + 2, i + 9), nil
            i = i + 10

        elseif two == "|r" then
            out[#out + 1] = two
            active, prev  = nil, nil
            i = i + 2

        elseif two == "|H" then
            -- Ссылка целиком: «|Hданные|hвидимый текст|h».
            local mid  = msg:find("|h", i + 2, true)
            local tail = mid and msg:find("|h", mid + 2, true)
            local stop = (tail and tail + 1) or (mid and mid + 1) or n
            out[#out + 1] = msg:sub(i, stop)
            prev = nil
            i = stop + 1

        elseif two == "|T" then
            local stop = msg:find("|t", i + 2, true)
            stop = stop and (stop + 1) or n
            out[#out + 1] = msg:sub(i, stop)
            prev = nil
            i = stop + 1

        else
            local hit
            local bucket = nameByByte[msg:byte(i)]
            if bucket and not IsWordByte(prev) then
                for _, name in ipairs(bucket) do
                    if msg:sub(i, i + #name - 1) == name
                       and not IsWordByte(msg:byte(i + #name)) then
                        hit = name
                        break
                    end
                end
            end

            if hit then
                -- Чужой цвет закрываем, свой открываем, чужой возвращаем:
                -- вложенных «|c» в разметке клиента не бывает.
                if active then out[#out + 1] = "|r" end
                out[#out + 1] = "|c" .. nameColor[hit] .. hit .. "|r"
                if active then out[#out + 1] = "|c" .. active end
                prev = nil
                i = i + #hit
            else
                out[#out + 1] = msg:sub(i, i)
                prev = msg:byte(i)
                i = i + 1
            end
        end
    end

    return table.concat(out)
end

-- Состав группы и фоновые статусы — два повода забыть кэш, и оба
