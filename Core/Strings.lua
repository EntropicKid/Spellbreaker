SB.Data = SB.Data or {}
SB.UI   = SB.UI or {}

-- ============================================================
-- ХОДЫ НА ЭКРАНЕ — ЭТО ВРЕМЯ
--
-- В расчётах ход остаётся ходом: счётчики эффектов, очередь, тики — всё
-- по-прежнему целые ходы, и ни одна формула об этом переводе не знает.
-- Меняется ТОЛЬКО подпись: «10 ход.» ничего не говорит о сцене, а
-- «1 мин.» сразу ставит происходящее во время.
--
-- Шесть секунд на ход — та же цена хода, что в самой игре: столько живёт
-- боевой раунд, и на неё же завязаны все длительности заклинаний, с
-- которых списана библиотека.
--
-- ЕДИНИЦЫ СОКРАЩЕНЫ С ТОЧКОЙ и потому не склоняются: «2 час.» — это
-- «2 час(а)», а не ошибка согласования. Пустые разряды не печатаются
-- вовсе: «1 мин.» вместо «0 час. 1 мин. 0 сек.».
-- ============================================================
SB.Data.SecondsPerTurn = 6

-- ============================================================
-- ВРЕМЯ ИЛИ ХОДЫ — ПО ТОМУ, КАК ИДЁТ ВРЕМЯ В СЦЕНЕ
--
-- Перевод ходов во время был сделан затем, что «10 ход.» ничего не
-- говорит о сцене, а «1 мин.» сразу ставит происходящее во время. Это
-- верно РОВНО ПОКА ВРЕМЯ ИДЁТ САМО.
--
-- В пошаговом режиме оно не идёт: ход длится столько, сколько его
-- отыгрывают, — минуту, десять, полчаса на спор о том, кто куда встал.
-- Подпись «18 сек.» там не приблизительна, а просто неверна: за эти
-- «восемнадцать секунд» реально проходит четверть часа, и планировать
-- по ним нельзя. Единица, в которой люди там считают, — ход.
--
-- Поэтому подпись СЛЕДУЕТ ЗА РЕЖИМОМ: свободный ход — время, пошаговый
-- — ходы. Обе формы живут в этих двух функциях, через которые и так
-- проходит весь показ длительностей в аддоне, поэтому переключение
-- обошлось без единой правки на местах.
-- ============================================================

--- Идёт ли сейчас пошаговый режим.
--- Отдельной функцией: спрашивают её обе формы подписи, и порядок
--- загрузки файлов тут ни при чём — вызов идёт во время работы.
local function InTurnMode()
    return (SB.TurnOrder and SB.TurnOrder.IsActive and SB.TurnOrder.IsActive())
        and true or false
end

--- Русское склонение: 1 ход, 2 хода, 5 ходов, 11 ходов.
--- Своими руками, а не через готовую библиотеку: слово ровно одно, и
--- тащить ради него зависимость незачем.
local function TurnWord(n)
    local ones, teens = n % 10, n % 100
    if teens >= 11 and teens <= 14 then return "ходов" end
    if ones == 1 then return "ход"  end
    if ones >= 2 and ones <= 4 then return "хода" end
    return "ходов"
end

--- «1 час. 5 мин. 42 сек.» — полная подпись для карточек и подсказок.
--- В пошаговом режиме — «3 хода» (см. врезку выше).
--- @param turns number  число ходов (не длительность в секундах!)
function SB.UI.TurnsAsTime(turns)
    if InTurnMode() then
        local n = math.max(0, math.floor(tonumber(turns) or 0))
        return n .. " " .. TurnWord(n)
    end
    return SB.UI.TurnsAsTimeFull(turns)
end

--- Та же подпись, но ВСЕГДА временем, независимо от режима. Нужна там,
--- где речь именно о времени, а не о длительности эффекта: например
--- «сколько эта сцена уже идёт» в панели Ведущего — там ходы уже
--- названы числом рядом, и повторять их вторым разом незачем.
function SB.UI.TurnsAsTimeFull(turns)
    local total = math.max(0, math.floor(tonumber(turns) or 0)) * SB.Data.SecondsPerTurn
    if total == 0 then return "0 сек." end

    local h = math.floor(total / 3600)
    local m = math.floor((total % 3600) / 60)
    local s = total % 60

    local parts = {}
    if h > 0 then parts[#parts + 1] = h .. " час." end
    if m > 0 then parts[#parts + 1] = m .. " мин." end
    if s > 0 then parts[#parts + 1] = s .. " сек." end
    return table.concat(parts, " ")
end

--- «1ч05м» / «1м06с» / «42с» — то же самое для мест, где на подпись
--- отведён угол иконки. Разрядов не больше двух: третий там не читается
--- ни при каком размере шрифта.
---
--- МЛАДШИЙ РАЗРЯД ОТБРАСЫВАЕТСЯ, КОГДА СТАРШИЙ ДВУЗНАЧНЫЙ: «10м06с» — это
--- шесть знаков, и в углу иконки они уже налезают на саму картинку. Да и
--- секунды при десяти минутах запаса — шум: подпись отвечает на вопрос
--- «скоро ли спадёт», а не «сколько ровно». Итог не длиннее пяти знаков
--- при любом числе ходов.
function SB.UI.TurnsAsTimeShort(turns)
    local n = math.max(0, math.floor(tonumber(turns) or 0))
    -- В ПОШАГОВОМ — ЧИСЛО И БУКВА «х». Полное «3 хода» в угол иконки не
    -- влезает ни при каком шрифте, а голое число читалось бы как
    -- секунды: рядом, в свободном ходу, там стоит именно «3с».
    if InTurnMode() then return n .. "х" end
    return SB.UI.SecondsAsTimeShort(n * SB.Data.SecondsPerTurn)
end

--- То же самое, но ИЗ СЕКУНД, а не из ходов. Нужна там, где время идёт
--- само и подпись обязана убывать посекундно (см.
--- SB.ActiveEffects.SecondsLeft): счётчик ходов даёт скачок в шесть
--- секунд, и на иконке это читается как замерший таймер.
function SB.UI.SecondsAsTimeShort(seconds)
    local total = math.max(0, math.floor(tonumber(seconds) or 0))
    if total == 0 then return "0с" end

    local h = math.floor(total / 3600)
    local m = math.floor((total % 3600) / 60)
    local s = total % 60

    if h > 0 then
        if m > 0 and h < 10 then return string.format("%dч%02dм", h, m) end
        return h .. "ч"
    end
    if m > 0 then
        if s > 0 and m < 10 then return string.format("%dм%02dс", m, s) end
        return m .. "м"
    end
    return s .. "с"
end

